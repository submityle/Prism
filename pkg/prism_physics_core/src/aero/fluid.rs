use glam::Vec3;

use super::field::Real;
use super::sanitize::{finite, non_negative, normalize, vec3};
use super::surface::FluidKind;

/// An oriented infinite fluid interface. The normal points from the fluid into
/// the exterior medium; water normally uses a world-up normal and a horizontal plane.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct FluidPlane {
    pub point: Vec3,
    pub normal: Vec3,
    pub density: Real,
}

impl FluidPlane {
    #[must_use]
    pub fn new(point: Vec3, normal: Vec3, density: Real) -> Self {
        Self {
            point,
            normal: normalize(normal, Vec3::Y),
            density: non_negative(density),
        }
    }

    #[must_use]
    pub fn horizontal(height: Real, density: Real) -> Self {
        Self::new(Vec3::new(0.0, finite(height), 0.0), Vec3::Y, density)
    }

    #[must_use]
    pub fn signed_height(&self, position: Vec3) -> Real {
        (vec3(position) - vec3(self.point)).dot(normalize(self.normal, Vec3::Y))
    }
}

/// Diagonal added-mass coefficients in body coordinates.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AddedMass {
    pub fluid: FluidKind,
    pub volume: Real,
    pub linear_coefficients: Vec3,
    pub angular_coefficients: Vec3,
    pub reference_radius: Real,
}

impl AddedMass {
    /// Body-space displaced-fluid mass, including immersion exactly once.
    #[must_use]
    pub fn mass_diagonal(&self, density: Real, immersion: Real) -> Vec3 {
        let scale =
            non_negative(density) * non_negative(self.volume) * super::sanitize::unit(immersion);
        vec3(
            Vec3::new(
                non_negative(self.linear_coefficients.x),
                non_negative(self.linear_coefficients.y),
                non_negative(self.linear_coefficients.z),
            ) * scale,
        )
    }

    /// Body-space added inertia, with the required radius-squared scaling.
    #[must_use]
    pub fn inertia_diagonal(&self, density: Real, immersion: Real) -> Vec3 {
        let radius = non_negative(self.reference_radius);
        let scale = non_negative(density)
            * non_negative(self.volume)
            * super::sanitize::unit(immersion)
            * radius
            * radius;
        vec3(
            Vec3::new(
                non_negative(self.angular_coefficients.x),
                non_negative(self.angular_coefficients.y),
                non_negative(self.angular_coefficients.z),
            ) * scale,
        )
    }

    /// Converts a body-space inverse mass diagonal to an implicit added-mass
    /// response without changing the body's authored mass properties.
    #[must_use]
    pub fn implicit_inverse_mass(
        &self,
        inverse_mass: Vec3,
        density: Real,
        immersion: Real,
    ) -> Vec3 {
        let added = self.mass_diagonal(density, immersion);
        Vec3::new(
            implicit_inverse(inverse_mass.x, added.x),
            implicit_inverse(inverse_mass.y, added.y),
            implicit_inverse(inverse_mass.z, added.z),
        )
    }

    /// Converts a body-space inverse inertia diagonal to an implicit response
    /// using the same radius-squared added inertia as the force evaluator.
    #[must_use]
    pub fn implicit_inverse_inertia(
        &self,
        inverse_inertia: Vec3,
        density: Real,
        immersion: Real,
    ) -> Vec3 {
        let added = self.inertia_diagonal(density, immersion);
        Vec3::new(
            implicit_inverse(inverse_inertia.x, added.x),
            implicit_inverse(inverse_inertia.y, added.y),
            implicit_inverse(inverse_inertia.z, added.z),
        )
    }
}

fn implicit_inverse(inverse: Real, added: Real) -> Real {
    let inverse = non_negative(inverse);
    let added = non_negative(added);
    if inverse == 0.0 {
        0.0
    } else {
        inverse / (1.0 + inverse * added)
    }
}

impl Default for AddedMass {
    fn default() -> Self {
        Self {
            fluid: FluidKind::Water,
            volume: 0.0,
            linear_coefficients: Vec3::ZERO,
            angular_coefficients: Vec3::ZERO,
            reference_radius: 0.0,
        }
    }
}

/// Coefficients for the Magnus force generated by spin through a fluid.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct MagnusParams {
    pub fluid: FluidKind,
    pub coefficient: Real,
    pub reference_area: Real,
    pub effective_radius: Real,
}

impl Default for MagnusParams {
    fn default() -> Self {
        Self {
            fluid: FluidKind::Air,
            coefficient: 0.0,
            reference_area: 0.0,
            effective_radius: 0.0,
        }
    }
}

/// A volume element used for deterministic partial-submersion quadrature.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BuoyancyVolume {
    pub local_center: Vec3,
    pub local_half_extents: Vec3,
    pub volume: Real,
    pub samples_per_axis: u8,
    pub fluid: FluidKind,
}

impl BuoyancyVolume {
    #[must_use]
    pub fn box_volume(local_center: Vec3, local_half_extents: Vec3, fluid: FluidKind) -> Self {
        let half_extents = Vec3::new(
            non_negative(local_half_extents.x),
            non_negative(local_half_extents.y),
            non_negative(local_half_extents.z),
        );
        Self {
            local_center,
            local_half_extents: half_extents,
            volume: 8.0 * half_extents.x * half_extents.y * half_extents.z,
            samples_per_axis: 4,
            fluid,
        }
    }

    #[must_use]
    pub fn with_volume(mut self, volume: Real) -> Self {
        self.volume = non_negative(volume);
        self
    }

    #[must_use]
    pub fn with_samples(mut self, samples_per_axis: u8) -> Self {
        self.samples_per_axis = samples_per_axis.clamp(1, 8);
        self
    }
}
