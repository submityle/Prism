#[cfg(test)]
mod tests {
    use super::super::microfacet::GgxIsotropic;
    use super::super::sampler::Rng;
    use super::super::Vec3;
    use super::*;

    /// Maps a table node index `i` to its cell-centre coordinate
    /// `(i + 0.5) / LUT_SIZE` in the open interval `(0, 1)`.
    fn node_center(i: usize) -> f32 {
        (i as f32 + 0.5) / LUT_SIZE as f32
    }

    /// Monte Carlo estimate of the white-Fresnel single-scatter directional
    /// albedo `E(cos_o, alpha)` via visible-normal sampling, whose throughput
    /// weight collapses to `G2(wo, wi) / G1(wo)`.
    fn mc_albedo(alpha: f32, cos_o: f32, rng: &mut Rng, samples: u32) -> f32 {
        let dist = GgxIsotropic { alpha };
        let normal = Vec3::new(0.0, 0.0, 1.0);
        let sin_o = (1.0 - cos_o * cos_o).max(0.0).sqrt();
        let wo = Vec3::new(sin_o, 0.0, cos_o);
        let g1o = dist.g1(cos_o);
        if g1o <= 0.0 {
            return 0.0;
        }
        let mut sum = 0.0f64;
        for _ in 0..samples {
            if let Some(h) = dist.sample_half_vector(wo, normal, rng) {
                let woh = wo.dot(h);
                if woh <= 0.0 {
                    continue;
                }
                let wi = wo.negate().reflect(h).normalize_or_zero();
                let cos_i = wi.z;
                if cos_i <= 0.0 {
                    continue;
                }
                sum += f64::from(dist.g2(cos_o, cos_i) / g1o);
            }
        }
        (sum / f64::from(samples)) as f32
    }

    /// Regenerates the baked table from a fresh furnace integral and checks it
    /// matches the committed constants. Run with `--nocapture` to print a fresh
    /// literal when the sampler changes.
    #[expect(
        clippy::print_stdout,
        clippy::needless_range_loop,
        reason = "test regenerates and prints a paste-ready baked LUT literal under --nocapture; the LUT is indexed on two axes"
    )]
    #[test]
    fn lut_matches_monte_carlo() {
        let mut rng = Rng::seed(0x5eed_1234);
        let samples = 1u32 << 16;
        let mut albedo = [[0.0f32; LUT_SIZE]; LUT_SIZE];
        let mut avg = [0.0f32; LUT_SIZE];
        for ai in 0..LUT_SIZE {
            let alpha = node_center(ai);
            let mut acc = 0.0f64;
            for ci in 0..LUT_SIZE {
                let cos_o = node_center(ci);
                let e = mc_albedo(alpha, cos_o, &mut rng, samples);
                albedo[ai][ci] = e;
                // Midpoint rule for 2 * integral E(mu) mu d mu over the row.
                acc += 2.0 * f64::from(e) * f64::from(cos_o) / f64::from(LUT_SIZE as u32);
            }
            avg[ai] = acc as f32;
        }

        // Emit a ready-to-paste literal (visible only under --nocapture).
        println!("const ALBEDO_DATA: [[f32; LUT_SIZE]; LUT_SIZE] = [");
        for row in &albedo {
            print!("    [");
            for v in row {
                print!("{v:.5}, ");
            }
            println!("],");
        }
        println!("];");
        print!("const AVG_ALBEDO_DATA: [f32; LUT_SIZE] = [");
        for v in &avg {
            print!("{v:.5}, ");
        }
        println!("];");

        // Verify the committed table reproduces the integral within MC noise.
        for ai in 0..LUT_SIZE {
            let alpha = node_center(ai);
            for ci in 0..LUT_SIZE {
                let cos_o = node_center(ci);
                let baked = directional_albedo(cos_o, alpha);
                assert!(
                    (baked - albedo[ai][ci]).abs() < 2.0e-2,
                    "albedo drift at alpha={alpha} cos={cos_o}: baked {baked} vs mc {}",
                    albedo[ai][ci]
                );
            }
            let baked_avg = average_albedo(alpha);
            assert!(
                (baked_avg - avg[ai]).abs() < 2.0e-2,
                "avg drift at alpha={alpha}: baked {baked_avg} vs mc {}",
                avg[ai]
            );
        }
    }

    /// Smooth surfaces lose no energy, so the compensation lobe must vanish.
    #[test]
    fn smooth_surface_needs_no_compensation() {
        assert!(average_albedo(0.0) > 0.98);
        assert!(multiscatter_lobe(0.6, 0.6, 0.0) < 1.0e-2);
    }

    /// Rough surfaces lose energy, so both the albedo deficit and the
    /// compensation lobe must be strictly positive.
    #[test]
    fn rough_surface_recovers_energy() {
        assert!(average_albedo(0.9) < 0.95);
        assert!(multiscatter_lobe(0.5, 0.5, 0.9) > 0.0);
    }
}
