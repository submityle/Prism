//! Multiple-scattering energy compensation for the isotropic `GGX` conductor.
//!
//! A single-scatter microfacet `BRDF` only accounts for light that leaves the
//! surface after exactly one bounce off a micro-facet. At high roughness a
//! large fraction of the energy instead bounces several times between facets
//! before escaping, and the single-scatter Smith masking term `G2` silently
//! discards all of it. The visible symptom is the classic one: rough metals
//! (and rough dielectrics) turn noticeably too dark and desaturated as
//! roughness rises, violating white-furnace energy conservation.
//!
//! Kulla and Conty ("Revisiting Physically Based Shading at Imageworks", 2017)
//! restore the missing energy with an added, nearly diffuse multiple-scattering
//! lobe whose magnitude is driven by the *directional albedo* of the
//! single-scatter lobe:
//!
//! ```text
//!   E(mu, alpha)  = white-Fresnel single-scatter directional albedo
//!   E_avg(alpha)  = 2 * integral_0^1 E(mu, alpha) * mu  d mu
//!   f_ms(mu_o, mu_i) = (1 - E(mu_o)) * (1 - E(mu_i)) / (pi * (1 - E_avg))
//! ```
//!
//! The lobe exactly makes up the energy deficit `1 - E` so a white furnace
//! integrates back to one. For a coloured conductor the multiple bounces are
//! each attenuated by the average `Fresnel` reflectance `F_avg`, giving the
//! per-channel multiple-scatter tint
//! `F_ms = F_avg^2 * E_avg / (1 - F_avg * (1 - E_avg))`, which also reproduces
//! the subtle saturation increase real rough metals show.
//!
//! `E` and `E_avg` are smooth functions, so they are baked into a small
//! [`LUT_SIZE`]`x`[`LUT_SIZE`] table (`alpha` by `cos_theta`) and bilinearly
//! interpolated at run time. The table is regenerated and checked against a
//! fresh `Monte Carlo` furnace integral by [`tests::lut_matches_monte_carlo`],
//! so the baked constants can never silently drift from the sampler they
//! describe. Lookups use only multiplies, adds, and a clamp — no transcendental
//! call — honouring the crate's determinism policy.

use super::Vec3;

/// Resolution of the directional-albedo lookup table along each axis
/// (`alpha` rows by `cos_theta` columns).
pub const LUT_SIZE: usize = 16;

/// Baked single-scatter directional albedo `E(mu, alpha)` under a white
/// (`F = 1`) `Fresnel` term. The outer index selects the `alpha` node, the
/// inner index the `cos_theta` node; both are cell centres at
/// `(i + 0.5) / LUT_SIZE`. Generated by [`tests::lut_matches_monte_carlo`].
const ALBEDO: [[f32; LUT_SIZE]; LUT_SIZE] = ALBEDO_DATA;

/// Baked cosine-weighted average albedo `E_avg(alpha)` for each `alpha` node,
/// `E_avg = 2 * integral E(mu) mu d mu`. Generated alongside [`ALBEDO`].
const AVG_ALBEDO: [f32; LUT_SIZE] = AVG_ALBEDO_DATA;

/// Linearly interpolates a value from one axis of the table given a continuous
/// coordinate `x` in `[0, 1]`, clamping to the first/last cell centre.
///
/// Returns the fractional node position `(index_lo, index_hi, frac)` so both
/// 1-D and 2-D lookups can share the clamping logic.
fn axis_weights(x: f32) -> (usize, usize, f32) {
    // Continuous node coordinate: node `i` sits at `(i + 0.5) / LUT_SIZE`.
    let t = (x * LUT_SIZE as f32 - 0.5).clamp(0.0, (LUT_SIZE - 1) as f32);
    let lo = t as usize;
    let hi = (lo + 1).min(LUT_SIZE - 1);
    (lo, hi, t - lo as f32)
}

/// The single-scatter directional albedo `E(cos_theta, alpha)` with white
/// `Fresnel`, bilinearly interpolated from the baked table and clamped to
/// `[0, 1]`.
#[must_use]
pub fn directional_albedo(cos_theta: f32, alpha: f32) -> f32 {
    let (a_lo, a_hi, a_f) = axis_weights(alpha);
    let (c_lo, c_hi, c_f) = axis_weights(cos_theta);
    let row_lo = ALBEDO[a_lo][c_lo] + (ALBEDO[a_lo][c_hi] - ALBEDO[a_lo][c_lo]) * c_f;
    let row_hi = ALBEDO[a_hi][c_lo] + (ALBEDO[a_hi][c_hi] - ALBEDO[a_hi][c_lo]) * c_f;
    (row_lo + (row_hi - row_lo) * a_f).clamp(0.0, 1.0)
}

/// The cosine-weighted average albedo `E_avg(alpha)`, linearly interpolated from
/// the baked table and clamped to `[0, 1]`.
#[must_use]
pub fn average_albedo(alpha: f32) -> f32 {
    let (lo, hi, f) = axis_weights(alpha);
    (AVG_ALBEDO[lo] + (AVG_ALBEDO[hi] - AVG_ALBEDO[lo]) * f).clamp(0.0, 1.0)
}

/// The scalar Kulla-Conty multiple-scattering lobe
/// `f_ms = (1 - E(mu_o)) * (1 - E(mu_i)) / (pi * (1 - E_avg))`.
///
/// Returns zero once `E_avg` reaches one (the smooth limit, where there is no
/// energy to recover), avoiding a divide-by-zero.
#[must_use]
pub fn multiscatter_lobe(cos_o: f32, cos_i: f32, alpha: f32) -> f32 {
    let e_avg = average_albedo(alpha);
    let denom = 1.0 - e_avg;
    if denom <= 1.0e-4 {
        return 0.0;
    }
    let e_o = directional_albedo(cos_o, alpha);
    let e_i = directional_albedo(cos_i, alpha);
    (1.0 - e_o) * (1.0 - e_i) / (super::PI * denom)
}

/// The per-channel multiple-scatter `Fresnel` tint
/// `F_ms = F_avg^2 * E_avg / (1 - F_avg * (1 - E_avg))`.
///
/// `f_avg` is the hemispherical-average `Fresnel` reflectance of the interface;
/// each additional bounce multiplies by `F_avg`, so the closed-form geometric
/// series gives the colour of the recovered energy.
#[must_use]
pub fn multiscatter_fresnel(f_avg: Vec3, alpha: f32) -> Vec3 {
    let e_avg = average_albedo(alpha);
    let one_minus = 1.0 - e_avg;
    let channel = |f: f32| -> f32 {
        let denom = 1.0 - f * one_minus;
        if denom <= 1.0e-4 {
            f
        } else {
            f * f * e_avg / denom
        }
    };
    Vec3::new(channel(f_avg.x), channel(f_avg.y), channel(f_avg.z))
}

