//! Multiple-scattering energy data for the rough dielectric interface.
//!
//! A single-scatter microfacet dielectric (frosted glass, see
//! [`crate::reference_pt::rough_dielectric`]) only transports light that
//! reflects or refracts off exactly one micro-facet. At high roughness a large
//! fraction of the energy instead bounces several times between facets before
//! escaping, and the single-scatter Smith masking term `G2` silently discards
//! all of it, so rough glass and water render visibly too dark. This module
//! supplies the directional-albedo data needed to add that energy back with a
//! Turquin-style multiplicative compensation
//! (E. Turquin, "Practical multiple scattering compensation for microfacet
//! models", 2019).
//!
//! Two quantities drive the compensation:
//!
//! - the *single-scatter directional albedo* `E(eta, alpha, mu)`, i.e. the
//!   total reflected-plus-transmitted energy a lossless
//!   (`reflectance = transmittance = 1`) rough dielectric sends out for a view
//!   cosine `mu` at relative index `eta` and `GGX` width `alpha`. This is baked
//!   into the trilinear [`ALBEDO`] table and regenerated/validated against a
//!   fresh `Monte Carlo` furnace integral by [`tests::lut_matches_monte_carlo`];
//! - the *smooth ceiling* `E_smooth(eta, mu)`, the alpha to zero limit of the
//!   same albedo. Because `PBRT` v4's radiance-mode transmitted lobe carries the
//!   `1 / eta^2` solid-angle compression, a lossless smooth interface does not
//!   integrate to one but to `R + (1 - R) / eta^2`, where `R` is the smooth
//!   `Fresnel` reflectance. The compensation restores the masking loss up to
//!   this physically correct ceiling rather than to one, so it never injects
//!   the energy the radiance measure legitimately removes.
//!
//! The base rough dielectric orients its shading frame toward the viewer and
//! applies the relative index as-is, so its directional albedo is identical for
//! exterior and interior incidence; a single table therefore covers both sides
//! of the interface. Lookups use only multiplies, adds, a clamp and a `sqrt`,
//! honouring the crate's determinism policy (no `sin`/`cos`/`exp`/`pow`).

use super::dielectric::fresnel_dielectric;

/// Number of relative-index nodes along the `eta` axis of [`ALBEDO`].
pub const ETA_SIZE: usize = 6;
/// Number of `GGX` width nodes along the `alpha` axis of [`ALBEDO`].
pub const ALPHA_SIZE: usize = 8;
/// Number of view-cosine nodes along the `mu` axis of [`ALBEDO`].
pub const MU_SIZE: usize = 8;

/// Smallest relative index covered by the baked table.
pub const ETA_MIN: f32 = 1.1;
/// Largest relative index covered by the baked table.
pub const ETA_MAX: f32 = 2.5;

/// Baked lossless single-scatter directional albedo `E(eta, alpha, mu)`.
///
/// The outer index selects the `eta` node, the middle index the `alpha` node,
/// the inner index the `mu` (view cosine) node. The `alpha` and `mu` nodes are
/// cell centres at `(i + 0.5) / N`; the `eta` nodes are cell centres mapped
/// into `[ETA_MIN, ETA_MAX]` at `ETA_MIN + (ETA_MAX - ETA_MIN) * (i + 0.5) /
/// ETA_SIZE`. Generated by
/// [`tests::lut_matches_monte_carlo`].
const ALBEDO: [[[f32; MU_SIZE]; ALPHA_SIZE]; ETA_SIZE] = ALBEDO_DATA;

/// Returns `x` squared, spelled out so the banned `powi`/`powf` are avoided.
fn sqr(x: f32) -> f32 {
    x * x
}

/// Maps a relative index `eta` to the normalized table coordinate in `[0, 1]`,
/// clamped so out-of-range indices resolve to the nearest baked node.
fn eta_unit(eta: f32) -> f32 {
    ((eta - ETA_MIN) / (ETA_MAX - ETA_MIN)).clamp(0.0, 1.0)
}

/// Linearly interpolates one axis of a cell-centred table of length `n` given a
/// continuous coordinate `x` in `[0, 1]`, clamping to the first/last cell.
///
/// Returns the fractional node position `(index_lo, index_hi, frac)` so the
/// trilinear lookup can share the clamping logic across all three axes.
fn axis_weights(x: f32, n: usize) -> (usize, usize, f32) {
    let t = (x * n as f32 - 0.5).clamp(0.0, (n - 1) as f32);
    let lo = t as usize;
    let hi = (lo + 1).min(n - 1);
    (lo, hi, t - lo as f32)
}

/// Linearly interpolates between `a` and `b` by `t`.
fn lerp(a: f32, b: f32, t: f32) -> f32 {
    a + (b - a) * t
}

/// The lossless single-scatter directional albedo `E(eta, alpha, mu)`,
/// trilinearly interpolated from the baked [`ALBEDO`] table and clamped to
/// `[0, 1]`.
///
/// `mu` is the absolute view cosine `|n·wo|`, `alpha` the `GGX` width, and
/// `eta` the relative index `eta_t / eta_i`.
#[must_use]
pub fn single_scatter_albedo(eta: f32, alpha: f32, mu: f32) -> f32 {
    let (e_lo, e_hi, e_f) = axis_weights(eta_unit(eta), ETA_SIZE);
    let (a_lo, a_hi, a_f) = axis_weights(alpha, ALPHA_SIZE);
    let (m_lo, m_hi, m_f) = axis_weights(mu, MU_SIZE);
    // Inner `mu` lerp at a fixed `(eta, alpha)` node.
    let along_mu = |e: usize, a: usize| lerp(ALBEDO[e][a][m_lo], ALBEDO[e][a][m_hi], m_f);
    // Middle `alpha` lerp at a fixed `eta` node.
    let along_alpha = |e: usize| lerp(along_mu(e, a_lo), along_mu(e, a_hi), a_f);
    // Outer `eta` lerp.
    lerp(along_alpha(e_lo), along_alpha(e_hi), e_f).clamp(0.0, 1.0)
}

/// The smooth-interface ceiling `E_smooth(eta, mu) = R + (1 - R) / eta^2`, the
/// alpha to zero limit of the directional albedo in `PBRT` radiance mode.
///
/// `R` is the smooth unpolarized `Fresnel` reflectance at view cosine `mu`
/// (exterior incidence, `eta_i = 1`), so the reflected share `R` stays in the
/// incident medium while the transmitted share `1 - R` is compressed by the
/// radiance-mode `1 / eta^2` solid-angle factor. Multiple scattering recovers
/// the masking loss up to this value, never past it.
#[must_use]
pub fn smooth_albedo(eta: f32, mu: f32) -> f32 {
    let r = fresnel_dielectric(mu, 1.0, eta);
    r + (1.0 - r) / sqr(eta)
}

/// The multiplicative multiple-scattering compensation factor for a rough
/// dielectric viewed at cosine `mu`.
///
/// Dividing the single-scatter lobe by its directional albedo and multiplying
/// by the smooth ceiling restores exactly the energy Smith masking drops, so a
/// lossless furnace integrates back to `E_smooth` instead of the darkened
/// single-scatter value. The factor is clamped to `[1, MAX_FACTOR]`: it can
/// never remove energy (`>= 1`), and the ceiling guards the near-grazing /
/// near-critical regime where the baked albedo is small.
#[must_use]
pub fn compensation_factor(eta: f32, alpha: f32, mu: f32) -> f32 {
    /// Upper bound on the boost, so a tiny baked albedo cannot explode the lobe.
    const MAX_FACTOR: f32 = 3.0;
    /// Floor on the denominator, matching the smallest trustworthy baked albedo.
    const MIN_ALBEDO: f32 = 0.05;
    let e = single_scatter_albedo(eta, alpha, mu).max(MIN_ALBEDO);
    let ceiling = smooth_albedo(eta, mu);
    (ceiling / e).clamp(1.0, MAX_FACTOR)
}

