#[cfg(test)]
mod tests {
    use super::super::rough_dielectric::RoughDielectric;
    use super::super::sampler::Rng;
    use super::super::Vec3;
    use super::*;

    /// The macroscopic surface normal used by the furnace integral (`+y`).
    const N: Vec3 = Vec3 {
        x: 0.0,
        y: 1.0,
        z: 0.0,
    };

    /// Maps an `alpha`/`mu` node index to its cell-centre coordinate
    /// `(i + 0.5) / n`.
    fn node_center(i: usize, n: usize) -> f32 {
        (i as f32 + 0.5) / n as f32
    }

    /// Maps a relative-index node index `i` to its sampling value in
    /// `[ETA_MIN, ETA_MAX]`, the cell centre `ETA_MIN + (ETA_MAX - ETA_MIN) *
    /// (i + 0.5) / ETA_SIZE`.
    fn eta_node(i: usize) -> f32 {
        ETA_MIN + (ETA_MAX - ETA_MIN) * (i as f32 + 0.5) / ETA_SIZE as f32
    }

    /// Monte Carlo estimate of the lossless single-scatter directional albedo
    /// `E(eta, alpha, mu)` (reflected plus transmitted) for a rough dielectric
    /// viewed at cosine `mu`, by importance-sampling the base lobe.
    fn mc_albedo(eta: f32, alpha: f32, mu: f32, rng: &mut Rng, samples: u32) -> f32 {
        let roughness = alpha.sqrt();
        let rd = RoughDielectric::new(eta, Vec3::ONE, Vec3::ONE, roughness);
        let sin_o = (1.0 - mu * mu).max(0.0).sqrt();
        let wo = Vec3::new(sin_o, mu, 0.0).normalize_or_zero();
        let mut sum = 0.0f64;
        for _ in 0..samples {
            if let Some(s) = rd.sample(wo, N, rng) {
                // Reflected samples stay above `N`, transmitted ones cross
                // below it; the albedo integral weights both by `|cos_i|`.
                let cos_i = N.dot(s.direction).abs();
                sum += f64::from(s.value.x * cos_i / s.pdf);
            }
        }
        (sum / f64::from(samples)) as f32
    }

    /// Regenerates the baked table from a fresh furnace integral and checks it
    /// matches the committed constants. Run with `--nocapture` to print a fresh
    /// literal when the sampler changes.
    #[test]
    fn lut_matches_monte_carlo() {
        let mut rng = Rng::seed(0x0d1e_1ec7);
        let samples = 1u32 << 16;
        let mut table = [[[0.0f32; MU_SIZE]; ALPHA_SIZE]; ETA_SIZE];
        for ei in 0..ETA_SIZE {
            let eta = eta_node(ei);
            for ai in 0..ALPHA_SIZE {
                let alpha = node_center(ai, ALPHA_SIZE);
                for mi in 0..MU_SIZE {
                    let mu = node_center(mi, MU_SIZE);
                    table[ei][ai][mi] = mc_albedo(eta, alpha, mu, &mut rng, samples);
                }
            }
        }

        // Emit a ready-to-paste literal (visible only under --nocapture).
        println!("const ALBEDO_DATA: [[[f32; MU_SIZE]; ALPHA_SIZE]; ETA_SIZE] = [");
        for eta_block in &table {
            println!("    [");
            for row in eta_block {
                print!("        [");
                for v in row {
                    print!("{v:.5}, ");
                }
                println!("],");
            }
            println!("    ],");
        }
        println!("];");

        // Verify the committed table reproduces the integral within MC noise.
        for ei in 0..ETA_SIZE {
            let eta = eta_node(ei);
            for ai in 0..ALPHA_SIZE {
                let alpha = node_center(ai, ALPHA_SIZE);
                for mi in 0..MU_SIZE {
                    let mu = node_center(mi, MU_SIZE);
                    let baked = single_scatter_albedo(eta, alpha, mu);
                    assert!(
                        (baked - table[ei][ai][mi]).abs() < 2.0e-2,
                        "albedo drift at eta={eta} alpha={alpha} mu={mu}: baked {baked} vs mc {}",
                        table[ei][ai][mi]
                    );
                }
            }
        }
    }

    /// The smooth ceiling must bracket the baked rough albedo and match the
    /// `alpha` to zero limit: a lossless smooth interface integrates to
    /// `R + (1 - R) / eta^2`, strictly below one for `eta > 1`.
    #[test]
    fn smooth_ceiling_is_consistent() {
        let mut rng = Rng::seed(0xbeef_cafe);
        for &eta in &[1.33f32, 1.5, 2.0] {
            for &mu in &[0.2f32, 0.6, 0.95] {
                let ceiling = smooth_albedo(eta, mu);
                assert!(ceiling < 1.0, "radiance-mode ceiling must stay below one");
                // A near-smooth furnace should land close to the analytic ceiling.
                let near_smooth = mc_albedo(eta, 0.02, mu, &mut rng, 1u32 << 16);
                assert!(
                    (near_smooth - ceiling).abs() < 3.0e-2,
                    "near-smooth albedo {near_smooth} should match ceiling {ceiling}",
                );
            }
        }
    }

    /// The compensation factor is unity for smooth surfaces (no masking loss)
    /// and strictly greater than one for rough ones (energy to recover).
    #[test]
    fn compensation_factor_recovers_energy() {
        assert!((compensation_factor(1.5, 0.02, 0.6) - 1.0).abs() < 5.0e-2);
        assert!(compensation_factor(1.5, 0.9, 0.6) > 1.05);
        assert!(compensation_factor(2.0, 0.9, 0.4) > 1.05);
    }
}
