    #[test]
    fn encode_decode_is_deterministic_and_validates_cross_references() {
        let asset = asset();
        asset.validate().expect("fixture is valid");
        let encoded = asset.encode().expect("encodes");
        assert_eq!(encoded, asset.encode().expect("encodes identically"));
        assert_eq!(
            VirtualGeometryAsset::decode(&encoded).expect("decodes"),
            asset
        );

        let mut invalid = asset;
        invalid.nodes[0].page = GeometryPageKey::new(7, 1);
        assert_eq!(
            invalid.validate(),
            Err(VirtualGeometryAssetError::MissingPage(
                GeometryPageKey::new(7, 1)
            ))
        );
    }

    #[test]
    fn validation_rejects_invalid_node_bounds_and_orphan_clusters() {
        let mut invalid_node = asset();
        invalid_node.nodes[0].bounds.half_extents[0] = -1.0;
        assert_eq!(
            invalid_node.validate(),
            Err(VirtualGeometryAssetError::InvalidNode(0))
        );

        let mut orphan = asset();
        orphan.pages[0].record.cluster_count = 0;
        assert_eq!(
            orphan.validate(),
            Err(VirtualGeometryAssetError::InvalidValue("orphan cluster"))
        );
    }

    #[test]
    fn decoder_rejects_truncation_and_trailing_bytes() {
        let encoded = asset().encode().expect("encodes");
        assert_eq!(
            VirtualGeometryAsset::decode(&encoded[..encoded.len() - 1]),
            Err(VirtualGeometryAssetError::Truncated)
        );
        let mut trailing = encoded.clone();
        trailing.push(0);
        assert_eq!(
            VirtualGeometryAsset::decode(&trailing),
            Err(VirtualGeometryAssetError::TrailingBytes)
        );
    }
