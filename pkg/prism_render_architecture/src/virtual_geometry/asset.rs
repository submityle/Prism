//! Versioned on-disk contract for paged virtual geometry.
//!
//! The builder owns cluster generation and compression; this module owns the
//! stable wire format consumed by streaming and runtime residency.  Payloads
//! are opaque bytes here so the same format can carry uncompressed data or a
//! backend-approved compressor such as GDeflate without putting I/O or GPU
//! code into the architecture crate.

use alloc::collections::BTreeMap;
use alloc::vec::Vec;
use core::fmt;

use crate::gpu_scene::SceneBounds;

use super::{ClusterNode, GeometryPageKey};

/// Eight-byte file signature for virtual-geometry assets.
pub const VIRTUAL_GEOMETRY_ASSET_MAGIC: [u8; 8] = *b"PRVGAS01";
/// Current serialized asset schema.
pub const VIRTUAL_GEOMETRY_ASSET_SCHEMA: u32 = 1;
/// Minimum page size accepted by the contract.
pub const MIN_VIRTUAL_GEOMETRY_PAGE_SIZE: u32 = 1024;
/// Recommended page size for shipped assets.
pub const DEFAULT_VIRTUAL_GEOMETRY_PAGE_SIZE: u32 = 64 * 1024;
const MAX_DECODE_RECORDS: u32 = 16 * 1024 * 1024;

/// Compression applied to one stored page payload.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
#[repr(u8)]
pub enum VirtualGeometryCompression {
    /// Payload bytes are directly addressable after the page is resident.
    None = 0,
    /// Payload is compressed with the runtime's GDeflate-compatible decoder.
    GDeflate = 1,
}

impl VirtualGeometryCompression {
    fn decode(value: u8) -> Result<Self, VirtualGeometryAssetError> {
        match value {
            0 => Ok(Self::None),
            1 => Ok(Self::GDeflate),
            _ => Err(VirtualGeometryAssetError::InvalidValue("compression")),
        }
    }
}

/// Asset-level metadata shared by all pages and hierarchy records.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct VirtualGeometryAssetHeader {
    /// Stable source geometry identity used by [`GeometryPageKey`].
    pub asset_id: u32,
    /// Serialized schema version.
    pub schema_version: u32,
    /// Fixed physical page size in bytes.
    pub page_size: u32,
    /// Hash of the builder settings and capability profile.
    pub build_settings_hash: [u8; 32],
    /// Hash of the authored mesh/build input.
    pub content_hash: [u8; 32],
    /// Bounds enclosing every hierarchy root.
    pub bounds: SceneBounds,
    /// Number of material slots referenced by clusters.
    pub material_slot_count: u32,
    /// Optional content identity of the standard fallback mesh.
    pub fallback_mesh_hash: [u8; 32],
}

impl VirtualGeometryAssetHeader {
    /// Creates a header with the current schema and the recommended page size.
    #[must_use]
    pub const fn new(
        asset_id: u32,
        bounds: SceneBounds,
        material_slot_count: u32,
        build_settings_hash: [u8; 32],
        content_hash: [u8; 32],
        fallback_mesh_hash: [u8; 32],
    ) -> Self {
        Self {
            asset_id,
            schema_version: VIRTUAL_GEOMETRY_ASSET_SCHEMA,
            page_size: DEFAULT_VIRTUAL_GEOMETRY_PAGE_SIZE,
            build_settings_hash,
            content_hash,
            bounds,
            material_slot_count,
            fallback_mesh_hash,
        }
    }
}

/// Metadata describing one streamed page. The payload itself lives in
/// [`VirtualGeometryPage::payload`].
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct VirtualGeometryPageRecord {
    /// Page address within the source asset.
    pub key: GeometryPageKey,
    /// Compression used by the stored payload.
    pub compression: VirtualGeometryCompression,
    /// Uncompressed byte count expected after decompression.
    pub uncompressed_size: u32,
    /// Streaming importance hint generated by the builder.
    pub priority: u16,
    /// First cluster descriptor backed by this page.
    pub cluster_start: u32,
    /// Number of cluster descriptors backed by this page.
    pub cluster_count: u16,
}

/// One cluster's location and GPU-facing geometry metadata.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct VirtualGeometryClusterRecord {
    /// Index of the hierarchy node represented by this cluster.
    pub node_index: u32,
    /// Page carrying the cluster payload.
    pub page: GeometryPageKey,
    /// Material slot used by the cluster.
    pub material_slot: u16,
    /// Quantized vertex count in the cluster.
    pub vertex_count: u16,
    /// Triangle count in the cluster.
    pub triangle_count: u16,
    /// Byte offset in the uncompressed page payload.
    pub payload_offset: u32,
    /// Byte length in the uncompressed page payload.
    pub payload_size: u32,
    /// Cluster-local/world-space bounds used by culling.
    pub bounds: SceneBounds,
    /// Normal cone axis XYZ and cosine cutoff W.
    pub normal_cone: [f32; 4],
}

/// A page record and its stored bytes.
#[derive(Clone, Debug, PartialEq)]
pub struct VirtualGeometryPage {
    /// Page metadata.
    pub record: VirtualGeometryPageRecord,
    /// Compressed or uncompressed bytes as stored on disk.
    pub payload: Vec<u8>,
}

/// Complete versioned virtual-geometry asset.
#[derive(Clone, Debug, PartialEq)]
pub struct VirtualGeometryAsset {
    /// Asset header.
    pub header: VirtualGeometryAssetHeader,
    /// Flat hierarchy node array.
    pub nodes: Vec<ClusterNode>,
    /// Root node indices into [`Self::nodes`].
    pub roots: Vec<u32>,
    /// Streamable pages in strictly increasing key order.
    pub pages: Vec<VirtualGeometryPage>,
    /// Cluster descriptors in the order referenced by page records.
    pub clusters: Vec<VirtualGeometryClusterRecord>,
}

impl VirtualGeometryAsset {
    /// Validates all cross-table invariants before serialization or streaming.
    pub fn validate(&self) -> Result<(), VirtualGeometryAssetError> {
        validate_header(&self.header)?;
        if self.nodes.is_empty() || self.roots.is_empty() {
            return Err(VirtualGeometryAssetError::InvalidValue("hierarchy roots"));
        }
        let hierarchy = super::ClusterHierarchy::new(self.nodes.clone(), self.roots.clone());
        if !hierarchy.is_well_formed() {
            return Err(VirtualGeometryAssetError::InvalidHierarchy);
        }
        let mut page_by_key = BTreeMap::new();
        for (page_index, page) in self.pages.iter().enumerate() {
            if page.record.key.asset != self.header.asset_id {
                return Err(VirtualGeometryAssetError::AssetIdMismatch(page.record.key));
            }
            if let Some(previous) = page_index
                .checked_sub(1)
                .and_then(|index| self.pages.get(index))
                .map(|page| page.record.key)
            {
                if page.record.key <= previous {
                    return Err(VirtualGeometryAssetError::PagesNotSorted);
                }
            }
            if page.payload.len() > self.header.page_size as usize
                || page.record.uncompressed_size == 0
                || page.record.uncompressed_size > self.header.page_size
            {
                return Err(VirtualGeometryAssetError::PageTooLarge(page.record.key));
            }
            if page.record.compression == VirtualGeometryCompression::None
                && page.record.uncompressed_size != page.payload.len() as u32
            {
                return Err(VirtualGeometryAssetError::PayloadSizeMismatch(
                    page.record.key,
                ));
            }
            let cluster_end = page
                .record
                .cluster_start
                .checked_add(u32::from(page.record.cluster_count))
                .ok_or(VirtualGeometryAssetError::InvalidValue("cluster range"))?;
            if cluster_end as usize > self.clusters.len() {
                return Err(VirtualGeometryAssetError::InvalidValue("cluster range"));
            }
            page_by_key.insert(page.record.key, page);
        }
        for (index, node) in self.nodes.iter().enumerate() {
            if !bounds_finite(&node.bounds) || !node.self_error.is_finite() || node.self_error < 0.0
            {
                return Err(VirtualGeometryAssetError::InvalidNode(index as u32));
            }
            let end = node
                .first_child
                .checked_add(node.child_count)
                .ok_or(VirtualGeometryAssetError::InvalidHierarchy)?;
            if node.child_count != 0 {
                for child in node.first_child..end {
                    let child_node = self.nodes[child as usize];
                    if child_node.self_error > node.self_error {
                        return Err(VirtualGeometryAssetError::NonMonotonicError {
                            parent: index as u32,
                            child,
                        });
                    }
                }
            }
            if node.page.asset != self.header.asset_id {
                return Err(VirtualGeometryAssetError::AssetIdMismatch(node.page));
            }
            if !page_by_key.contains_key(&node.page) {
                return Err(VirtualGeometryAssetError::MissingPage(node.page));
            }
        }

        let mut cluster_coverage = vec![false; self.clusters.len()];
        for page in &self.pages {
            let cluster_start = page.record.cluster_start as usize;
            let cluster_end = page
                .record
                .cluster_start
                .checked_add(u32::from(page.record.cluster_count))
                .ok_or(VirtualGeometryAssetError::InvalidValue("cluster range"))?;
            if cluster_end as usize > self.clusters.len() {
                return Err(VirtualGeometryAssetError::InvalidValue("cluster range"));
            }
            for (index, cluster) in self.clusters[cluster_start..cluster_end as usize]
                .iter()
                .enumerate()
            {
                cluster_coverage[cluster_start + index] = true;
                if cluster.page != page.record.key {
                    return Err(VirtualGeometryAssetError::InvalidValue("page clusters"));
                }
            }
        }

        if cluster_coverage.iter().any(|covered| !covered) {
            return Err(VirtualGeometryAssetError::InvalidValue("orphan cluster"));
        }
        for cluster in &self.clusters {
            if cluster.node_index as usize >= self.nodes.len()
                || !page_by_key.contains_key(&cluster.page)
            {
                return Err(VirtualGeometryAssetError::InvalidValue("cluster reference"));
            }
            if u32::from(cluster.material_slot) >= self.header.material_slot_count
                || cluster.vertex_count > 64
                || cluster.triangle_count > 128
            {
                return Err(VirtualGeometryAssetError::InvalidCluster(
                    cluster.node_index,
                ));
            }
            if !bounds_finite(&cluster.bounds)
                || !cluster.normal_cone.iter().all(|value| value.is_finite())
                || !(-1.0..=1.0).contains(&cluster.normal_cone[3])
            {
                return Err(VirtualGeometryAssetError::InvalidCluster(
                    cluster.node_index,
                ));
            }
            let page = page_by_key
                .get(&cluster.page)
                .ok_or(VirtualGeometryAssetError::MissingPage(cluster.page))?;
            let end = cluster
                .payload_offset
                .checked_add(cluster.payload_size)
                .ok_or(VirtualGeometryAssetError::InvalidCluster(
                    cluster.node_index,
                ))?;
            if end > page.record.uncompressed_size {
                return Err(VirtualGeometryAssetError::InvalidCluster(
                    cluster.node_index,
                ));
            }
        }
        Ok(())
    }

    /// Encodes the asset into deterministic little-endian bytes.
    pub fn encode(&self) -> Result<Vec<u8>, VirtualGeometryAssetError> {
        self.validate()?;
        let mut writer = Writer::default();
        writer.bytes(&VIRTUAL_GEOMETRY_ASSET_MAGIC);
        writer.u32(self.header.schema_version);
        writer.u32(self.header.asset_id);
        writer.u32(self.header.page_size);
        writer.bytes(&self.header.build_settings_hash);
        writer.bytes(&self.header.content_hash);
        write_bounds(&mut writer, self.header.bounds);
        writer.u32(self.header.material_slot_count);
        writer.bytes(&self.header.fallback_mesh_hash);
        writer.len(self.nodes.len())?;
        for node in &self.nodes {
            write_bounds(&mut writer, node.bounds);
            writer.f32(node.self_error);
            writer.u32(node.page.asset);
            writer.u32(node.page.page);
            writer.u32(node.first_child);
            writer.u32(node.child_count);
        }
        writer.len(self.roots.len())?;
        for root in &self.roots {
            writer.u32(*root);
        }
        writer.len(self.pages.len())?;
        for page in &self.pages {
            writer.u32(page.record.key.asset);
            writer.u32(page.record.key.page);
            writer.u8(page.record.compression as u8);
            writer.u32(page.record.uncompressed_size);
            writer.u16(page.record.priority);
            writer.u32(page.record.cluster_start);
            writer.u16(page.record.cluster_count);
            writer.len(page.payload.len())?;
            writer.bytes(&page.payload);
        }
        writer.len(self.clusters.len())?;
        for cluster in &self.clusters {
            writer.u32(cluster.node_index);
            writer.u32(cluster.page.asset);
            writer.u32(cluster.page.page);
            writer.u16(cluster.material_slot);
            writer.u16(cluster.vertex_count);
            writer.u16(cluster.triangle_count);
            writer.u32(cluster.payload_offset);
            writer.u32(cluster.payload_size);
            write_bounds(&mut writer, cluster.bounds);
            for value in cluster.normal_cone {
                writer.f32(value);
            }
        }
        Ok(writer.into_bytes())
    }

    /// Decodes and validates one complete asset from bytes.
    pub fn decode(bytes: &[u8]) -> Result<Self, VirtualGeometryAssetError> {
        let mut reader = Reader::new(bytes);
        if reader.bytes::<8>()? != VIRTUAL_GEOMETRY_ASSET_MAGIC {
            return Err(VirtualGeometryAssetError::InvalidMagic);
        }
        let schema_version = reader.u32()?;
        if schema_version != VIRTUAL_GEOMETRY_ASSET_SCHEMA {
            return Err(VirtualGeometryAssetError::UnsupportedSchema(schema_version));
        }
        let asset_id = reader.u32()?;
        let page_size = reader.u32()?;
        let build_settings_hash = reader.bytes::<32>()?;
        let content_hash = reader.bytes::<32>()?;
        let bounds = read_bounds(&mut reader)?;
        let material_slot_count = reader.u32()?;
        let fallback_mesh_hash = reader.bytes::<32>()?;
        let header = VirtualGeometryAssetHeader {
            asset_id,
            schema_version,
            page_size,
            build_settings_hash,
            content_hash,
            bounds,
            material_slot_count,
            fallback_mesh_hash,
        };
        validate_header(&header)?;

        let node_count = reader.count()?;
        let mut nodes = Vec::with_capacity(node_count as usize);
        for _ in 0..node_count {
            nodes.push(ClusterNode {
                bounds: read_bounds(&mut reader)?,
                self_error: reader.f32()?,
                page: GeometryPageKey::new(reader.u32()?, reader.u32()?),
                first_child: reader.u32()?,
                child_count: reader.u32()?,
            });
        }
        let root_count = reader.count()?;
        let mut roots = Vec::with_capacity(root_count as usize);
        for _ in 0..root_count {
            roots.push(reader.u32()?);
        }
        let page_count = reader.count()?;
        let mut pages = Vec::with_capacity(page_count as usize);
        for _ in 0..page_count {
            let key = GeometryPageKey::new(reader.u32()?, reader.u32()?);
            let compression = VirtualGeometryCompression::decode(reader.u8()?)?;
            let uncompressed_size = reader.u32()?;
            let priority = reader.u16()?;
            let cluster_start = reader.u32()?;
            let cluster_count = reader.u16()?;
            let payload_len = reader.count()?;
            if payload_len > page_size {
                return Err(VirtualGeometryAssetError::PageTooLarge(key));
            }
            pages.push(VirtualGeometryPage {
                record: VirtualGeometryPageRecord {
                    key,
                    compression,
                    uncompressed_size,
                    priority,
                    cluster_start,
                    cluster_count,
                },
                payload: reader.bytes_vec(payload_len as usize)?,
            });
        }
        let cluster_count = reader.count()?;
        let mut clusters = Vec::with_capacity(cluster_count as usize);
        for _ in 0..cluster_count {
            let node_index = reader.u32()?;
            let page = GeometryPageKey::new(reader.u32()?, reader.u32()?);
            let material_slot = reader.u16()?;
            let vertex_count = reader.u16()?;
            let triangle_count = reader.u16()?;
            let payload_offset = reader.u32()?;
            let payload_size = reader.u32()?;
            let bounds = read_bounds(&mut reader)?;
            let mut normal_cone = [0.0; 4];
            for value in &mut normal_cone {
                *value = reader.f32()?;
            }
            clusters.push(VirtualGeometryClusterRecord {
                node_index,
                page,
                material_slot,
                vertex_count,
                triangle_count,
                payload_offset,
                payload_size,
                bounds,
                normal_cone,
            });
        }
        let asset = Self {
            header,
            nodes,
            roots,
            pages,
            clusters,
        };
        asset.validate()?;
        if !reader.is_empty() {
            return Err(VirtualGeometryAssetError::TrailingBytes);
        }
        Ok(asset)
    }
}

/// Failure while validating or decoding a virtual-geometry asset.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum VirtualGeometryAssetError {
    /// Header signature does not match the format.
    InvalidMagic,
    /// Schema is newer or otherwise unsupported.
    UnsupportedSchema(u32),
    /// Header contains an invalid value.
    InvalidValue(&'static str),
    /// Hierarchy child/root references are invalid.
    InvalidHierarchy,
    /// A hierarchy node contains a non-finite or negative error bound.
    InvalidNode(u32),
    /// Parent error is smaller than a child error.
    NonMonotonicError { parent: u32, child: u32 },
    /// Node/page references another asset identity.
    AssetIdMismatch(GeometryPageKey),
    /// A hierarchy or cluster references a page absent from the page table.
    MissingPage(GeometryPageKey),
    /// Page keys are not strictly increasing.
    PagesNotSorted,
    /// Stored payload exceeds the configured page size.
    PageTooLarge(GeometryPageKey),
    /// Uncompressed page payload length disagrees with its metadata.
    PayloadSizeMismatch(GeometryPageKey),
    /// Cluster metadata violates the fixed cluster contract.
    InvalidCluster(u32),
    /// Input ended before a complete field was read.
    Truncated,
    /// A count would exceed the decoder's hard allocation cap.
    CountTooLarge(u32),
    /// Bytes remained after the final table.
    TrailingBytes,
}

impl fmt::Display for VirtualGeometryAssetError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidMagic => f.write_str("invalid virtual-geometry asset magic"),
            Self::UnsupportedSchema(version) => {
                write!(f, "unsupported virtual-geometry schema {version}")
            }
            Self::InvalidValue(field) => write!(f, "invalid virtual-geometry field {field}"),
            Self::InvalidHierarchy => f.write_str("invalid virtual-geometry hierarchy"),
            Self::InvalidNode(node) => write!(f, "invalid virtual-geometry node {node}"),
            Self::NonMonotonicError { parent, child } => {
                write!(
                    f,
                    "hierarchy error is non-monotonic at parent {parent}, child {child}"
                )
            }
            Self::AssetIdMismatch(key) => write!(f, "page key {:?} belongs to another asset", key),
            Self::MissingPage(key) => {
                write!(f, "page {:?} is missing from the asset page table", key)
            }
            Self::PagesNotSorted => f.write_str("virtual-geometry pages are not sorted"),
            Self::PageTooLarge(key) => write!(f, "page {:?} exceeds the configured page size", key),
            Self::PayloadSizeMismatch(key) => {
                write!(f, "uncompressed payload size mismatch for page {:?}", key)
            }
            Self::InvalidCluster(node) => {
                write!(f, "invalid virtual-geometry cluster for node {node}")
            }
            Self::Truncated => f.write_str("truncated virtual-geometry asset"),
            Self::CountTooLarge(count) => {
                write!(f, "virtual-geometry record count {count} is too large")
            }
            Self::TrailingBytes => f.write_str("trailing bytes after virtual-geometry asset"),
        }
    }
}

fn validate_header(header: &VirtualGeometryAssetHeader) -> Result<(), VirtualGeometryAssetError> {
    if header.schema_version != VIRTUAL_GEOMETRY_ASSET_SCHEMA
        || header.page_size < MIN_VIRTUAL_GEOMETRY_PAGE_SIZE
        || !header.page_size.is_power_of_two()
        || header.material_slot_count == 0
        || !bounds_finite(&header.bounds)
    {
        return Err(VirtualGeometryAssetError::InvalidValue("header"));
    }
    Ok(())
}

fn bounds_finite(bounds: &SceneBounds) -> bool {
    bounds
        .center
        .iter()
        .chain(bounds.half_extents.iter())
        .chain(core::iter::once(&bounds.radius))
        .all(|value| value.is_finite())
        && bounds.radius >= 0.0
        && bounds.half_extents.iter().all(|value| *value >= 0.0)
}

fn write_bounds(writer: &mut Writer, bounds: SceneBounds) {
    for value in bounds.center {
        writer.f32(value);
    }
    writer.f32(bounds.radius);
    for value in bounds.half_extents {
        writer.f32(value);
    }
    writer.f32(bounds._padding);
}

fn read_bounds(reader: &mut Reader<'_>) -> Result<SceneBounds, VirtualGeometryAssetError> {
    Ok(SceneBounds {
        center: [reader.f32()?, reader.f32()?, reader.f32()?],
        radius: reader.f32()?,
        half_extents: [reader.f32()?, reader.f32()?, reader.f32()?],
        _padding: reader.f32()?,
    })
}

#[derive(Default)]
struct Writer {
    bytes: Vec<u8>,
}

impl Writer {
    fn u8(&mut self, value: u8) {
        self.bytes.push(value);
    }

    fn u16(&mut self, value: u16) {
        self.bytes.extend_from_slice(&value.to_le_bytes());
    }

    fn u32(&mut self, value: u32) {
        self.bytes.extend_from_slice(&value.to_le_bytes());
    }

    fn f32(&mut self, value: f32) {
        self.u32(value.to_bits());
    }

    fn bytes(&mut self, value: &[u8]) {
        self.bytes.extend_from_slice(value);
    }

    fn len(&mut self, value: usize) -> Result<(), VirtualGeometryAssetError> {
        self.u32(
            u32::try_from(value).map_err(|_| VirtualGeometryAssetError::CountTooLarge(u32::MAX))?,
        );
        Ok(())
    }

    fn into_bytes(self) -> Vec<u8> {
        self.bytes
    }
}

struct Reader<'a> {
    bytes: &'a [u8],
    cursor: usize,
}

impl<'a> Reader<'a> {
    fn new(bytes: &'a [u8]) -> Self {
        Self { bytes, cursor: 0 }
    }

    fn take(&mut self, length: usize) -> Result<&'a [u8], VirtualGeometryAssetError> {
        let end = self
            .cursor
            .checked_add(length)
            .ok_or(VirtualGeometryAssetError::Truncated)?;
        let slice = self
            .bytes
            .get(self.cursor..end)
            .ok_or(VirtualGeometryAssetError::Truncated)?;
        self.cursor = end;
        Ok(slice)
    }

    fn bytes<const N: usize>(&mut self) -> Result<[u8; N], VirtualGeometryAssetError> {
        self.take(N)?
            .try_into()
            .map_err(|_| VirtualGeometryAssetError::Truncated)
    }

    fn bytes_vec(&mut self, length: usize) -> Result<Vec<u8>, VirtualGeometryAssetError> {
        Ok(self.take(length)?.to_vec())
    }

    fn u8(&mut self) -> Result<u8, VirtualGeometryAssetError> {
        Ok(self.take(1)?[0])
    }

    fn u16(&mut self) -> Result<u16, VirtualGeometryAssetError> {
        Ok(u16::from_le_bytes(self.bytes()?))
    }

    fn u32(&mut self) -> Result<u32, VirtualGeometryAssetError> {
        Ok(u32::from_le_bytes(self.bytes()?))
    }

    fn f32(&mut self) -> Result<f32, VirtualGeometryAssetError> {
        Ok(f32::from_bits(self.u32()?))
    }

    fn count(&mut self) -> Result<u32, VirtualGeometryAssetError> {
        let count = self.u32()?;
        if count > MAX_DECODE_RECORDS {
            return Err(VirtualGeometryAssetError::CountTooLarge(count));
        }
        Ok(count)
    }

    fn is_empty(&self) -> bool {
        self.cursor == self.bytes.len()
    }
}

