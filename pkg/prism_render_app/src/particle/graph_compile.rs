//! Bounded authoring compilation, separate from device resource materialization.

use super::{EmberAssetRevision, EmberCompiledGraphRegistry, GraphAssetRef};
use prism_render_architecture::particle::{
    asset_registry::EmberCompiledGraphRegistryError,
    compiler::{compile_with_data_interfaces, CompileError, CompiledGraph, StageModule},
    graph::GraphIr,
    modules::{DataInterface, EmberModule},
};
use std::{
    collections::BTreeMap,
    panic::{catch_unwind, AssertUnwindSafe},
    sync::{
        atomic::{AtomicBool, Ordering},
        mpsc::{self, Receiver},
        Arc, Mutex,
    },
    thread::{self, JoinHandle},
};

/// A module owned by an asynchronous authoring request.
pub struct EmberGraphStageModule {
    /// Index into the source graph's stages; input order within a stage is preserved.
    pub stage_index: usize,
    /// Thread-safe plugin, including its immutable specialization inputs.
    pub module: Arc<dyn EmberModule + Send + Sync>,
}

/// Immutable compilation input. Publish a new revision when any plugin input changes.
///
/// Retain the same `Arc` for idempotent requests. A graph-only hash cannot identify
/// custom module or data-interface implementations and is deliberately not used.
pub struct EmberGraphSource {
    /// Complete graph and its platform/shading specialization.
    pub graph: GraphIr,
    /// Ordered stage modules.
    pub modules: Vec<EmberGraphStageModule>,
    /// External sampling code and resource declarations.
    pub data_interfaces: Vec<Arc<dyn DataInterface + Send + Sync>>,
}

/// Admission limits. These bound queue cardinality and published shader size,
/// not arbitrary temporary allocations inside host-supplied plugin callbacks.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct EmberGraphCompileBudget {
    /// Number of tracked graphs, including terminal results retained for inspection.
    pub max_graphs: usize,
    /// Maximum stages in one request.
    pub max_stages: usize,
    /// Maximum modules in one request.
    pub max_modules: usize,
    /// Maximum interfaces in one request.
    pub max_data_interfaces: usize,
    /// Maximum validated generated WGSL bytes allowed for publication.
    pub max_generated_source_bytes: usize,
}

impl EmberGraphCompileBudget {
    /// Default authoring budget; at most one worker runs process-wide.
    pub const DEFAULT: Self = Self {
        max_graphs: 32,
        max_stages: 256,
        max_modules: 1024,
        max_data_interfaces: 128,
        max_generated_source_bytes: 4 * 1024 * 1024,
    };

    fn valid(self) -> bool {
        self.max_graphs > 0
            && self.max_stages > 0
            && self.max_modules > 0
            && self.max_data_interfaces > 0
            && self.max_generated_source_bytes > 0
    }
}

impl Default for EmberGraphCompileBudget {
    fn default() -> Self {
        Self::DEFAULT
    }
}

/// Request rejected before spawning work or changing the latest desired graph.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum EmberGraphCompileRequestError {
    /// Every budget dimension must be nonzero.
    InvalidBudget,
    /// Cancel an unneeded tracked graph before admitting a new graph.
    GraphCapacity,
    /// An input dimension exceeds its explicit limit.
    SourceLimit {
        /// Dimension that exceeded its limit.
        kind: &'static str,
        /// Requested count.
        actual: usize,
        /// Admission limit.
        limit: usize,
    },
    /// An older request cannot supersede newer source.
    StaleRevision {
        /// Current source revision.
        expected: u64,
        /// Incoming source revision.
        actual: u64,
    },
    /// Equal source revisions must reference the exact same immutable input.
    RevisionConflict,
    /// The per-service request identity space has been exhausted.
    TicketExhausted,
}

/// Failure of one admitted compile. The last published graph is preserved.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum EmberGraphCompileError {
    /// Graph, plugin declarations or generated WGSL failed validation.
    Compile(CompileError),
    /// Host plugin code unwound; it did not run on the frame thread.
    PluginPanicked,
    /// The OS could not create the worker.
    WorkerSpawn(String),
    /// The worker exited without returning a result.
    WorkerDisconnected,
    /// Generated WGSL exceeds the publication budget.
    GeneratedSourceLimit {
        /// Generated byte length.
        actual: usize,
        /// Configured byte limit.
        limit: usize,
    },
    /// An external publisher changed this graph while compilation was pending.
    PublicationChanged,
    /// Atomic registry publication was rejected.
    Publication(EmberCompiledGraphRegistryError),
}

/// Identity of one desired source, distinct even after cancel/remove/reinsert.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct EmberGraphCompileTicket {
    /// Stable graph asset reference.
    pub graph: GraphAssetRef,
    /// Host-owned monotonically increasing source revision.
    pub source_revision: u64,
    sequence: u64,
}

/// Observable compilation state for the latest source only.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum EmberGraphCompilePhase {
    /// Admitted; may replace an older queued revision without spawning a worker.
    Queued,
    /// Compiling on the bounded worker.
    Compiling,
    /// Validated and atomically published to the CPU registry.
    Ready {
        /// Revision extracted into RenderApp for device materialization.
        publication: EmberAssetRevision,
    },
    /// Explicit retry or a newer source revision is required; no per-frame retry storm.
    Failed(EmberGraphCompileError),
}

/// Latest request identity and phase, retained until cancellation or supersession.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EmberGraphCompileStatus {
    /// Latest desired source identity.
    pub ticket: EmberGraphCompileTicket,
    /// Current phase.
    pub phase: EmberGraphCompilePhase,
}

struct Desired {
    status: EmberGraphCompileStatus,
    source: Arc<EmberGraphSource>,
    expected_publication: Option<EmberAssetRevision>,
}

struct Active {
    ticket: EmberGraphCompileTicket,
    receiver: Mutex<Receiver<Result<CompiledGraph, EmberGraphCompileError>>>,
    worker: JoinHandle<()>,
}

// A resource can be replaced/dropped while a plugin is running. Do not join it
// on the frame thread or allow replacement resources to create unbounded workers.
static COMPILER_BUSY: AtomicBool = AtomicBool::new(false);

struct WorkerPermit;

impl Drop for WorkerPermit {
    fn drop(&mut self) {
        COMPILER_BUSY.store(false, Ordering::Release);
    }
}

pub(super) struct GraphCompiler {
    budget: EmberGraphCompileBudget,
    desired: BTreeMap<GraphAssetRef, Desired>,
    active: Option<Active>,
    sequence: u64,
}

impl Default for GraphCompiler {
    fn default() -> Self {
        Self::new(EmberGraphCompileBudget::DEFAULT)
    }
}

impl GraphCompiler {
    pub(super) const fn new(budget: EmberGraphCompileBudget) -> Self {
        Self {
            budget,
            desired: BTreeMap::new(),
            active: None,
            sequence: 0,
        }
    }

    pub(super) fn with_budget(
        budget: EmberGraphCompileBudget,
    ) -> Result<Self, EmberGraphCompileRequestError> {
        if !budget.valid() {
            return Err(EmberGraphCompileRequestError::InvalidBudget);
        }
        Ok(Self::new(budget))
    }

    pub(super) fn request(
        &mut self,
        registry: &EmberCompiledGraphRegistry,
        graph: GraphAssetRef,
        source_revision: u64,
        source: Arc<EmberGraphSource>,
    ) -> Result<EmberGraphCompileTicket, EmberGraphCompileRequestError> {
        if let Some(current) = self.desired.get(&graph) {
            let expected = current.status.ticket.source_revision;
            if source_revision < expected {
                return Err(EmberGraphCompileRequestError::StaleRevision {
                    expected,
                    actual: source_revision,
                });
            }
            if source_revision == expected {
                return if Arc::ptr_eq(&current.source, &source) {
                    Ok(current.status.ticket)
                } else {
                    Err(EmberGraphCompileRequestError::RevisionConflict)
                };
            }
        } else if self.desired.len() >= self.budget.max_graphs {
            return Err(EmberGraphCompileRequestError::GraphCapacity);
        }
        for (kind, actual, limit) in [
            ("stages", source.graph.stages.len(), self.budget.max_stages),
            ("modules", source.modules.len(), self.budget.max_modules),
            (
                "data_interfaces",
                source.data_interfaces.len(),
                self.budget.max_data_interfaces,
            ),
        ] {
            if actual > limit {
                return Err(EmberGraphCompileRequestError::SourceLimit {
                    kind,
                    actual,
                    limit,
                });
            }
        }
        self.sequence = self
            .sequence
            .checked_add(1)
            .ok_or(EmberGraphCompileRequestError::TicketExhausted)?;
        let ticket = EmberGraphCompileTicket {
            graph,
            source_revision,
            sequence: self.sequence,
        };
        self.desired.insert(
            graph,
            Desired {
                status: EmberGraphCompileStatus {
                    ticket,
                    phase: EmberGraphCompilePhase::Queued,
                },
                source,
                expected_publication: registry.get(graph).map(|entry| entry.revision()),
            },
        );
        Ok(ticket)
    }

    pub(super) fn status(&self, graph: GraphAssetRef) -> Option<&EmberGraphCompileStatus> {
        self.desired.get(&graph).map(|desired| &desired.status)
    }

    pub(super) fn cancel(&mut self, graph: GraphAssetRef) -> bool {
        self.desired.remove(&graph).is_some()
    }

    pub(super) fn cancel_all(&mut self) {
        self.desired.clear();
    }

    pub(super) fn retry(&mut self, ticket: EmberGraphCompileTicket) -> bool {
        let Some(desired) = self.desired.get_mut(&ticket.graph) else {
            return false;
        };
        if desired.status.ticket != ticket
            || !matches!(desired.status.phase,
            EmberGraphCompilePhase::Failed(ref error) if *error != EmberGraphCompileError::PublicationChanged)
        {
            return false;
        }
        desired.status.phase = EmberGraphCompilePhase::Queued;
        true
    }

    pub(super) fn poll(&mut self, registry: &mut EmberCompiledGraphRegistry) -> usize {
        let mut published = 0;
        if self
            .active
            .as_ref()
            .is_some_and(|active| active.worker.is_finished())
        {
            let active = self.active.take().expect("finished active worker");
            let result = active
                .receiver
                .lock()
                .unwrap_or_else(|poison| poison.into_inner())
                .try_recv()
                .unwrap_or(Err(EmberGraphCompileError::WorkerDisconnected));
            // is_finished guarantees joining cannot wait for plugin execution.
            let _ = active.worker.join();
            if let Some(desired) = self
                .desired
                .get_mut(&active.ticket.graph)
                .filter(|desired| desired.status.ticket == active.ticket)
            {
                let result = if registry
                    .get(active.ticket.graph)
                    .map(|entry| entry.revision())
                    != desired.expected_publication
                {
                    Err(EmberGraphCompileError::PublicationChanged)
                } else {
                    result
                };
                desired.status.phase = match result {
                    Ok(compiled) => match registry.publish(active.ticket.graph, compiled) {
                        Ok(publication) => {
                            published += 1;
                            EmberGraphCompilePhase::Ready { publication }
                        }
                        Err(error) => EmberGraphCompilePhase::Failed(
                            EmberGraphCompileError::Publication(error),
                        ),
                    },
                    Err(error) => EmberGraphCompilePhase::Failed(error),
                };
            }
        }
        if self.active.is_some() {
            return published;
        }
        let Some(desired) = self
            .desired
            .values_mut()
            .filter(|desired| matches!(desired.status.phase, EmberGraphCompilePhase::Queued))
            .min_by_key(|desired| desired.status.ticket.sequence)
        else {
            return published;
        };
        if COMPILER_BUSY
            .compare_exchange(false, true, Ordering::Acquire, Ordering::Relaxed)
            .is_err()
        {
            return published;
        }
        let permit = WorkerPermit;
        let source = desired.source.clone();
        let limit = self.budget.max_generated_source_bytes;
        let (sender, receiver) = mpsc::sync_channel(1);
        let worker = thread::Builder::new()
            .name("ember-authoring-compile".into())
            .spawn(move || {
                let _permit = permit;
                let result = catch_unwind(AssertUnwindSafe(|| {
                    let modules: Vec<_> = source
                        .modules
                        .iter()
                        .map(|module| StageModule {
                            stage_index: module.stage_index,
                            module: module.module.as_ref(),
                        })
                        .collect();
                    let interfaces: Vec<&dyn DataInterface> = source
                        .data_interfaces
                        .iter()
                        .map(|interface| interface.as_ref() as &dyn DataInterface)
                        .collect();
                    let compiled =
                        compile_with_data_interfaces(&source.graph, &modules, &interfaces)
                            .map_err(EmberGraphCompileError::Compile)?;
                    if compiled.source.len() > limit {
                        return Err(EmberGraphCompileError::GeneratedSourceLimit {
                            actual: compiled.source.len(),
                            limit,
                        });
                    }
                    Ok(compiled)
                }))
                .unwrap_or(Err(EmberGraphCompileError::PluginPanicked));
                // A replaced service may have dropped the last other source
                // reference. Keep the permit while plugin destructors run too.
                drop(source);
                let _ = sender.send(result);
            });
        match worker {
            Ok(worker) => {
                desired.status.phase = EmberGraphCompilePhase::Compiling;
                self.active = Some(Active {
                    ticket: desired.status.ticket,
                    receiver: Mutex::new(receiver),
                    worker,
                });
            }
            Err(error) => {
                desired.status.phase = EmberGraphCompilePhase::Failed(
                    EmberGraphCompileError::WorkerSpawn(error.to_string()),
                )
            }
        }
        published
    }
}

