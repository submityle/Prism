#[test]
fn nested_pcg_hash_and_top_24_bit_rank_match_fixed_goldens() {
    // Fixed words and f32 bit patterns, not expectations generated by the code
    // under test. These cover wrapping, hash nesting, tuple order, and seeds.
    let cases = [
        (0, 0, 0, 0x30be_035e, 0x3e42_f80c),
        (0, 1, 0, 0xe92a_518a, 0x3f69_2a51),
        (0, 0, 1, 0x5e63_01b0, 0x3ebc_c602),
        (0, 1, 1, 0xb192_1cde, 0x3f31_921c),
        (42, 7, 3, 0x20b0_fddf, 0x3e02_c3f4),
        (u32::MAX, u32::MAX, u32::MAX, 0x8f62_5239, 0x3f0f_6252),
        (
            0x1234_5678,
            0x9abc_def0,
            0x1357_9bdf,
            0xb5e4_c848,
            0x3f35_e4c8,
        ),
        (1, 7, 3, 0x5338_97c7, 0x3ea6_712e),
        (0, 7, 3, 0x372b_d388, 0x3e5c_af4c),
        (0, 3, 7, 0xeb98_822f, 0x3f6b_9882),
    ];
    for (seed, proxy_id, cluster_id, word, rank_bits) in cases {
        let policy = DensityPolicy::new(0.5, 0.1, seed, 0.0).unwrap();
        assert_eq!(pcg_hash(pcg_hash(proxy_id ^ seed) ^ cluster_id), word);
        assert_eq!(
            policy.sample_rank(proxy_id, cluster_id).to_bits(),
            rank_bits
        );
    }
}

#[test]
fn ranks_are_repeatable_half_open_and_24_bit_quantized() {
    for seed in [0, 1, 42, u32::MAX] {
        let policy = DensityPolicy::new(0.5, 0.1, seed, 0.0).unwrap();
        for proxy_id in 0..1024 {
            for cluster_id in [0, 7, u32::MAX] {
                let rank = policy.sample_rank(proxy_id, cluster_id);
                assert!((0.0..1.0).contains(&rank));
                assert_eq!(rank * 16_777_216.0, (rank * 16_777_216.0).trunc());
                assert_eq!(rank, policy.sample_rank(proxy_id, cluster_id));
            }
        }
    }
}

#[test]
fn seed_and_both_ordered_tuple_components_affect_rank() {
    let a = DensityPolicy::default();
    let b = DensityPolicy::new(1.0, 0.1, 1, 0.0).unwrap();
    assert_ne!(a.sample_rank(7, 3), b.sample_rank(7, 3));
    assert_ne!(a.sample_rank(7, 3), a.sample_rank(8, 3));
    assert_ne!(a.sample_rank(7, 3), a.sample_rank(7, 4));
    assert_ne!(a.sample_rank(7, 3), a.sample_rank(3, 7));
    // Curve parameters are deliberately not identity inputs.
    let c = DensityPolicy::new(0.0, 1.0, 0, f32::MAX).unwrap();
    assert_eq!(a.sample_rank(7, 3), c.sample_rank(7, 3));
}

#[test]
fn repeated_tuples_and_dense_reordering_keep_correlated_coverage() {
    let policy = DensityPolicy::new(0.25, 0.5, 42, 0.0).unwrap();
    let camera = camera([0.0; 3], 100.0);
    let a = proxy([0.0; 3], 100.0);
    let mut repeated_tuple = a;
    repeated_tuple.position = [20.0, 30.0, 40.0];
    repeated_tuple.radius = 20.0;
    repeated_tuple.geometric_error = 30.0;
    repeated_tuple.max_distance = 50.0;
    repeated_tuple.flags = u32::MAX;
    let mut other = a;
    other.proxy_id = 11;
    let before = [a, other, repeated_tuple];
    let after = [repeated_tuple, a, other];
    let coverage = policy.coverage(&a, &camera);
    assert!(coverage > 0.0 && coverage < 1.0);
    assert_eq!(coverage, policy.coverage(&repeated_tuple, &camera));
    for instance in before {
        let relocated = after.iter().find(|p| **p == instance).unwrap();
        assert_eq!(
            policy.coverage(&instance, &camera),
            policy.coverage(relocated, &camera)
        );
    }
}

