use super::*;
use crate::FrustumPlane;

fn camera(position: [f32; 3], max_distance: f32) -> VisibilityInput {
    VisibilityInput::from_projection_scale(
        position,
        [FrustumPlane::new([0.0, 0.0, 0.0], 1.0); 6],
        1.0,
        max_distance,
    )
}

fn proxy(position: [f32; 3], max_distance: f32) -> ProxyInstance {
    ProxyInstance::new(7, 3, position, 1.0, 1.0, max_distance)
}

fn assert_close(actual: f32, expected: f32) {
    assert!(
        (actual - expected).abs() <= 2.0e-5,
        "expected {expected}, got {actual}"
    );
}

#[test]
