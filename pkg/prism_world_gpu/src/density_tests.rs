#[test]
fn density_transition_uses_smoothstep_and_is_continuous() {
    let instance = proxy([0.0; 3], 100.0);
    let camera = camera([0.0; 3], 100.0);
    let transition = 0.25;
    let base = DensityPolicy::new(0.0, transition, 42, 0.0).unwrap();
    let start = base.sample_rank(7, 3) * (1.0 - transition);
    for (fraction, expected) in [
        (0.0, 0.0),
        (0.25, 0.15625),
        (0.5, 0.5),
        (0.75, 0.84375),
        (1.0, 1.0),
    ] {
        let policy =
            DensityPolicy::new(start + fraction * transition, transition, 42, 0.0).unwrap();
        assert_close(policy.coverage(&instance, &camera), expected);
    }
    for edge in [start, start + transition] {
        let low = DensityPolicy::new(edge - 1.0e-5, transition, 42, 0.0).unwrap();
        let high = DensityPolicy::new(edge + 1.0e-5, transition, 42, 0.0).unwrap();
        assert!(
            (high.coverage(&instance, &camera) - low.coverage(&instance, &camera)).abs() < 1.0e-6
        );
    }
}

#[test]
fn narrow_transition_matches_widened_mathematical_curve() {
    let instance = ProxyInstance::new(77, 3, [0.0; 3], 1.0, 1.0, 4.0);
    let camera = camera([0.0; 3], 4.0);
    for transition in [1.0e-7, 1.0e-4, 0.1, 1.0] {
        let density = f32::from_bits(0x3f42_4e42);
        let policy = DensityPolicy::new(density, transition, 0, 0.0).unwrap();
        // Widen before multiplying/subtracting: this oracle does not reproduce
        // the production f32 rearrangement or its former rounded-product bug.
        let r = f64::from(policy.sample_rank(77, 3));
        let t = f64::from(transition);
        let q = ((f64::from(density) - r * (1.0 - t)) / t).clamp(0.0, 1.0);
        assert_close(
            policy.coverage(&instance, &camera),
            (q * q * (3.0 - 2.0 * q)) as f32,
        );
    }
}

#[test]
fn tiny_distance_preserves_subnormal_differences_and_coordinates() {
    let minimum = f32::MIN_POSITIVE;
    let limit = minimum * 1.5;
    let policy = DensityPolicy::new(1.0, 1.0, 0, limit).unwrap();
    let origin = camera([0.0; 3], limit);
    assert_close(
        policy.coverage(&proxy([minimum, 0.0, 0.0], limit), &origin),
        7.0 / 27.0,
    );
    for sign in [-1.0, 1.0] {
        assert_close(
            policy.coverage(&proxy([sign * minimum / 2.0, 0.0, 0.0], limit), &origin),
            20.0 / 27.0,
        );
    }
    let adjacent = f32::from_bits(minimum.to_bits() + 1);
    assert_close(
        policy.coverage(
            &proxy([adjacent, 0.0, 0.0], limit),
            &camera([minimum, 0.0, 0.0], limit),
        ),
        1.0,
    );
    // Large identical coordinates must subtract before applying the boost.
    assert_eq!(
        policy.coverage(&proxy([f32::MAX; 3], limit), &camera([f32::MAX; 3], limit)),
        1.0
    );
}

