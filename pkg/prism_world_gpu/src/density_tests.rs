#[test]
fn smoothstep_flushes_subnormal_results_and_intermediate_underflow() {
    // 2^-64 squared is subnormal, and its smoothstep result is below the
    // minimum normal. At 2^-63 the square and the result are both normal.
    let below = f32::from_bits(63 << 23);
    let above = f32::from_bits(64 << 23);
    assert!((below * below).is_subnormal());
    assert!(above.is_normal() && (above * above).is_normal());
    for c in [
        -0.0,
        0.0,
        f32::from_bits(1),
        f32::MIN_POSITIVE,
        1.0e-20,
        below,
    ] {
        assert_eq!(smoothstep01(c).to_bits(), 0, "c={c}");
    }
    assert_eq!(smoothstep01(above), 3.0 * f32::MIN_POSITIVE);
    assert_eq!(smoothstep01(0.5), 0.5);
    assert_eq!(smoothstep01(1.0), 1.0);
}

#[test]
fn accepted_normal_density_can_produce_zero_or_normal_coverage() {
    let instance = proxy([0.0; 3], 1.0);
    let camera = camera([0.0; 3], 1.0);
    for density in [f32::MIN_POSITIVE, 1.0e-20] {
        let policy = DensityPolicy::new(density, 1.0, 0, 0.0).unwrap();
        assert_eq!(policy.coverage(&instance, &camera).to_bits(), 0);
    }
    let density = 1.0e-19;
    let policy = DensityPolicy::new(density, 1.0, 0, 0.0).unwrap();
    let expected = density * density * (3.0 - 2.0 * density);
    assert!(expected.is_normal());
    assert_eq!(policy.coverage(&instance, &camera), expected);
}

#[test]
fn final_product_flushes_subnormal_and_underflow_but_preserves_normal() {
    let policy = DensityPolicy::new(1.0e-19, 1.0, 0, 4.0).unwrap();
    let camera = camera([0.0; 3], 4.0);
    let quality = smoothstep01(policy.density());
    let normal_product = quality * 0.5;
    let subnormal_product = quality * 0.15625;
    assert!(quality.is_normal());
    assert!(normal_product.is_normal());
    assert!(subnormal_product.is_subnormal());
    assert_eq!(
        policy.coverage(&proxy([2.0, 0.0, 0.0], 4.0), &camera),
        normal_product
    );
    assert_eq!(
        policy
            .coverage(&proxy([3.0, 0.0, 0.0], 4.0), &camera)
            .to_bits(),
        0
    );

    let nearest_inside = f32::from_bits(4.0_f32.to_bits() - 1);
    let distance_c = (4.0 - nearest_inside) / 4.0;
    assert!(smoothstep01(distance_c).is_normal());
    assert_eq!(quality * smoothstep01(distance_c), 0.0);
    assert_eq!(
        policy
            .coverage(&proxy([nearest_inside, 0.0, 0.0], 4.0), &camera)
            .to_bits(),
        0
    );
}

