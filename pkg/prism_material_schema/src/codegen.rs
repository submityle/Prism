//! Deterministic code generation from the surface schema (design doc §17.5, S2).
//!
//! Stage S1 only *parity-checked* the hand-written layout against this schema.
//! Stage S2 flips the dependency: the schema becomes the generator. The two
//! emitters here turn the validated [`SurfaceSchema`] into the exact source text
//! of two previously hand-maintained twins:
//!
//! * [`emit_wesl_unpack`] — the GPU word-heap decoder
//!   (`prism_render_scene/src/shaders/material_unpack.wesl`): the lobe-bit
//!   constants, the neutral surface, `prism_packed_word_count` and
//!   `prism_unpack_surface`.
//! * [`emit_rust_layout`] — the CPU layout constants and lobe table consumed by
//!   `prism_render_material::surface` (`SURFACE_CORE_WORDS`, `SURFACE_MAX_WORDS`,
//!   the canonical [`SURFACE_LOBES`](crate) table, …).
//!
//! Both emitters are pure functions of the schema, so the generated files are
//! committed and a freshness test (`regenerate == committed`) turns any drift
//! into a red build. Byte parity of the hand-written `surface.rs` struct image
//! is still guarded by the S1 gate in `prism_render_material`, so the schema →
//! Rust layout → WESL chain is transitively byte-exact.
//!
//! The emitters are intentionally *textual*: they never shell out to `rustfmt`
//! or a WESL formatter, so output is reproducible on any host with no toolchain
//! beyond this crate. The layout they encode is small and regular (a 4-word
//! lobe quantum, low-bit-first), which keeps the generated text review-friendly.

use alloc::format;
use alloc::string::{String, ToString};
use alloc::vec::Vec;
use core::fmt::Write as _;

use crate::{FieldType, SurfaceSchema};

/// A machine-readable banner marking a file as generated. Both emitters start
/// with it so humans and tooling can detect a hand edit at a glance.
const GENERATED_BANNER_LINE: &str =
    "DO NOT EDIT — generated by `prism-material-codegen` from schema/surface.toml.";

/// The exact command that regenerates every product; embedded in each banner.
const REGEN_COMMAND: &str =
    "cargo run -p prism_material_schema --bin prism-material-codegen -- write";

/// Format an `f32` default as a source float literal with a mandatory decimal
/// point, identical for both WESL and Rust (`1 -> 1.0`, `0.1 -> 0.1`). A plain
/// `{}` can drop the point (`1`), which is a type error in WESL `f32` context,
/// so this guarantees one.
fn float_literal(v: f32) -> String {
    let s = format!("{v:?}");
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}

/// Assert the schema uses a single uniform lobe word count. Both twins encode
/// the stride as one constant (`PRISM_SURFACE_LOBE_WORDS` / `SURFACE_LOBE_WORDS`)
/// and advance a cursor by it per present lobe; a non-uniform schema would make
/// that constant a lie. The schema validator already fixes 4-word lobes, so this
/// is a defensive guard for a future schema change, surfaced as a clear panic in
/// the generator rather than silently wrong code.
fn uniform_lobe_words(schema: &SurfaceSchema) -> u32 {
    let mut words: Option<u32> = None;
    for lobe in &schema.lobes {
        match words {
            None => words = Some(lobe.words),
            Some(w) => assert_eq!(
                w, lobe.words,
                "codegen requires a uniform lobe word count; lobe `{}` has {} (expected {})",
                lobe.id, lobe.words, w
            ),
        }
    }
    words.unwrap_or(0)
}

/// All defined lobe bits OR-ed together (`(1 << count) - 1` for contiguous
/// slots, computed from the actual slots so a sparse registry still works).
fn all_lobe_bits(schema: &SurfaceSchema) -> u32 {
    schema
        .lobes
        .iter()
        .fold(0u32, |acc, l| acc | (1u32 << l.registry_slot))
}

