/// The §17.2 lobe-level energy policy: the rollup of the lobe's field-level
/// `energy_policy` column, `coupled` dominating `independent` dominating
/// `none`.
///
/// This is the *generator* side of the rule
/// `prism_material_pcm::EnergyPolicy::roll_up` applies at runtime — one rule,
/// so a hand-copied built-in catalogue cannot drift from the schema.
#[must_use]
fn lobe_energy_policy(lobe: &Lobe) -> EnergyPolicy {
    let mut rolled = EnergyPolicy::None;
    for field in &lobe.fields {
        rolled = match (rolled, field.energy_policy) {
            (EnergyPolicy::Coupled, _) | (_, EnergyPolicy::Coupled) => EnergyPolicy::Coupled,
            (EnergyPolicy::Independent, _) | (_, EnergyPolicy::Independent) => {
                EnergyPolicy::Independent
            }
            (EnergyPolicy::None, EnergyPolicy::None) => EnergyPolicy::None,
        };
    }
    rolled
}

/// The schema spelling of an energy policy, as it appears in the generated
/// table (`prism_material_pcm::EnergyPolicy::parse` reads it back).
#[must_use]
const fn energy_policy_str(policy: EnergyPolicy) -> &'static str {
    match policy {
        EnergyPolicy::Coupled => "coupled",
        EnergyPolicy::Independent => "independent",
        EnergyPolicy::None => "none",
    }
}

/// Emit the generated Rust layout module consumed by
/// `prism_render_material::surface` (constants, `LobeMask` layout facts, and
/// the canonical lobe table).
///
/// The output is byte-stable and ends with a trailing newline. It deliberately
/// contains only schema-derived layout facts the hand-written typed structs are
/// checked against: word counts, lobe bits and regions, the worst-case word
/// count, and the canonical `(id, mask_const, registry_slot, words)` table in
/// pack order. Small `const fn` accessors are emitted with the facts so no
/// hand-written list can become a second source of truth.
#[must_use]
pub fn emit_rust_layout(schema: &SurfaceSchema) -> String {
    fn emit_response_lobe(
        output: &mut String,
        id: &str,
        supported: bool,
        ignored_reason: Option<&str>,
    ) {
        let _ = writeln!(output, "    ResponseLobeLayout {{");
        let _ = writeln!(output, "        id: {id:?},");
        let _ = writeln!(output, "        supported: {supported},");
        if let Some(reason) = ignored_reason {
            let inline_reason = format!("        ignored_reason: Some({reason:?}),");
            if inline_reason.chars().count() <= RUSTFMT_MAX_WIDTH {
                let _ = writeln!(output, "{inline_reason}");
            } else {
                let _ = writeln!(output, "        ignored_reason: Some(");
                let _ = writeln!(output, "            {reason:?},");
                output.push_str("        ),\n");
            }
        } else {
            output.push_str("        ignored_reason: None,\n");
        }
        output.push_str("    },\n");
    }

    fn emit_response_ignored_field(output: &mut String, owner: &str, name: &str, reason: &str) {
        let inline = format!(
            "    ResponseIgnoredFieldLayout {{ lobe: {owner}, name: {name:?}, reason: {reason:?} }},"
        );
        if inline.chars().count() <= RUSTFMT_MAX_WIDTH {
            let _ = writeln!(output, "{inline}");
            return;
        }

        let _ = writeln!(output, "    ResponseIgnoredFieldLayout {{");
        let _ = writeln!(output, "        lobe: {owner},");
        let _ = writeln!(output, "        name: {name:?},");
        let _ = writeln!(output, "        reason: {reason:?},");
        output.push_str("    },\n");
    }

    fn emit_string_slice_field(output: &mut String, field: &str, values: &[String]) {
        let inline = format!("        {field}: &[{}],", values.join(", "));
        if inline.chars().count() <= RUSTFMT_MAX_WIDTH {
            let _ = writeln!(output, "{inline}");
            return;
        }

        let _ = writeln!(output, "        {field}: &[");
        for value in values {
            let _ = writeln!(output, "            {value},");
        }
        output.push_str("        ],\n");
    }

    let core_words = schema.core.words;
    let max_lobe_words = max_lobe_words(schema);
    let count = schema.lobe_count();
    let max_words = schema.packed_len_words(all_lobe_bits(schema));
    let lobes = schema.canonical_lobes();

    let mut o = String::with_capacity(2048);
    let _ = writeln!(o, "// {GENERATED_BANNER_LINE}");
    let _ = writeln!(o, "// Regenerate: {REGEN_COMMAND}");
    o.push_str("//! Generated über-BSDF surface layout facts (design doc §17.5, stage S2).\n");
    o.push_str("//!\n");
    o.push_str("//! The single declarative source of truth is `schema/surface.toml` in\n");
    o.push_str("//! `prism_material_schema`. This module exports the layout constants and the\n");
    o.push_str(
        "//! canonical lobe table so the hand-written typed structs in `surface.rs` can be\n",
    );
    o.push_str(
        "//! checked against — never diverge from — the schema. Edit the schema, not this.\n",
    );
    o.push('\n');
    o.push_str("/// Schema format version for this generated surface layout.\n");
    let _ = writeln!(
        o,
        "pub const SURFACE_SCHEMA_VERSION: u32 = {};",
        schema.schema_version
    );
    o.push_str("/// Runtime material ABI version owned by `schema/surface.toml`.\n");
    let _ = writeln!(
        o,
        "pub const SURFACE_ABI_VERSION: u32 = {};",
        schema.abi_version
    );
    o.push('\n');
    o.push_str("/// Number of `u32` words in the always-present surface core.\n");
    let _ = writeln!(o, "pub const SURFACE_CORE_WORDS: usize = {core_words};");
    o.push_str("/// Widest per-lobe word footprint in the schema.\n");
    o.push_str("///\n");
    o.push_str("/// Lobes are **variable length** (§4.4 \"变长打包\"):\n");
    o.push_str("/// [`crate::SurfaceParameterBlock::pack`]\n");
    o.push_str("/// advances the write cursor by each present lobe's own footprint, exposed\n");
    o.push_str("/// per slot in [`SURFACE_LOBE_WORDS_BY_SLOT`]. This constant is therefore\n");
    o.push_str("/// the largest quantum, useful for worst-case bounds — never a packing\n");
    o.push_str("/// stride.\n");
    let _ = writeln!(o, "pub const SURFACE_LOBE_WORDS: usize = {max_lobe_words};");
    o.push_str("/// Per-lobe `u32` word footprint indexed by `LobeMask` bit index\n");
    o.push_str("/// (`registry_slot`). The layout is two dense segments (§4.5 constraint 2):\n");
    o.push_str("/// canonical `KHR` slots from 0 and extension slots from\n");
    o.push_str("/// `EXTENSION_SLOT_BASE`, with the gap reserved. Undefined slots read 0, so\n");
    o.push_str("/// `SURFACE_LOBE_WORDS_BY_SLOT[bit.trailing_zeros()]` is the stride for that\n");
    o.push_str("/// lobe. Summing the present entries plus [`SURFACE_CORE_WORDS`] gives\n");
    o.push_str("/// `SurfaceParameterBlock::packed_len_words`.\n");
    let slot_span = lobes
        .iter()
        .map(|lobe| lobe.registry_slot as usize + 1)
        .max()
        .unwrap_or(0);
    let mut slot_words = alloc::vec![0usize; slot_span];
    for lobe in &lobes {
        let slot = lobe.registry_slot as usize;
        assert!(
            slot < slot_words.len(),
            "lobe `{}` registry_slot {} exceeds the slot span {}",
            lobe.id,
            lobe.registry_slot,
            slot_span
        );
        slot_words[slot] = lobe.words as usize;
    }
    // Emit the array in the shape `rustfmt` would leave it in, so running
    // `cargo fmt` over the generated file is a no-op and the freshness gate
    // (`tests/codegen_freshness.rs`) keeps meaning "committed == regenerated".
    let slot_words = slot_words
        .iter()
        .map(usize::to_string)
        .collect::<Vec<_>>()
        .join(", ");
    let declaration = format!("pub const SURFACE_LOBE_WORDS_BY_SLOT: [usize; {slot_span}] =");
    let one_line = format!("{declaration} [{slot_words}];");
    if one_line.chars().count() > RUSTFMT_MAX_WIDTH {
        let _ = writeln!(o, "{declaration}");
        let _ = writeln!(o, "    [{slot_words}];");
    } else {
        let _ = writeln!(o, "{one_line}");
    }
    o.push_str("/// Number of defined optional lobes (equals `LobeMask::COUNT`).\n");
    let _ = writeln!(o, "pub const SURFACE_LOBE_COUNT: u32 = {count};");
    o.push_str(
        "/// Fully-loaded worst case: core plus every lobe. The WESL decoder gathers into\n",
    );
    o.push_str("/// an `array<u32, SURFACE_MAX_WORDS>`.\n");
    let _ = writeln!(o, "pub const SURFACE_MAX_WORDS: usize = {max_words};");
    o.push('\n');

    // LobeMask's bit assignments, namespace regions, count and canonical pack
    // order are all derived facts. Emit them in a separate impl so the type and
    // behaviour-oriented methods can stay hand-written in `surface.rs` while
    // schema changes cannot drift from a duplicated bit list.
    o.push_str("/// Schema-derived optional-lobe mask facts.\n");
    o.push_str("impl crate::surface::LobeMask {\n");
    for lobe in &lobes {
        let _ = writeln!(
            o,
            "    /// Bit for the `{}` lobe (schema registry slot {}).",
            lobe.id, lobe.registry_slot
        );
        let _ = writeln!(
            o,
            "    pub const {}: Self = Self(1u32 << {});",
            lobe.mask_const, lobe.registry_slot
        );
    }

    let khr_lobes = lobes
        .iter()
        .copied()
        .filter(|lobe| lobe.namespace.is_openpbr_core())
        .collect::<Vec<_>>();
    let extension_lobes = lobes
        .iter()
        .copied()
        .filter(|lobe| !lobe.namespace.is_openpbr_core())
        .collect::<Vec<_>>();

    fn emit_region_mask(o: &mut String, name: &str, lobes: &[&Lobe]) {
        if lobes.is_empty() {
            let _ = writeln!(o, "    pub const {name}: Self = Self(0);");
            return;
        }
        if lobes.len() <= 3 {
            let expression = lobes
                .iter()
                .map(|lobe| format!("Self::{}.0", lobe.mask_const))
                .collect::<Vec<_>>()
                .join(" | ");
            let declaration = format!("    pub const {name}: Self = Self({expression});");
            if declaration.chars().count() > RUSTFMT_MAX_WIDTH {
                let _ = writeln!(o, "    pub const {name}: Self =");
                let _ = writeln!(o, "        Self({expression});");
            } else {
                let _ = writeln!(o, "{declaration}");
            }
            return;
        }

        let _ = writeln!(o, "    pub const {name}: Self = Self(");
        for (index, lobe) in lobes.iter().enumerate() {
            let suffix = if index + 1 == lobes.len() { "," } else { "" };
            if index == 0 {
                let _ = writeln!(o, "        Self::{}.0{suffix}", lobe.mask_const);
            } else {
                let _ = writeln!(o, "            | Self::{}.0{suffix}", lobe.mask_const);
            }
        }
        o.push_str("    );\n");
    }

    o.push_str("\n    /// All `OpenPBR` specification-core lobe bits.\n");
    emit_region_mask(&mut o, "KHR_REGION", &khr_lobes);

    o.push_str("\n    /// All non-`KHR` extension lobe bits.\n");
    emit_region_mask(&mut o, "EXTENSION_REGION", &extension_lobes);

    o.push_str("\n    /// Number of distinct lobe bits defined by the schema.\n");
    let _ = writeln!(o, "    pub const COUNT: u32 = {count};");

    o.push_str("\n    /// The mask containing every schema-defined lobe bit.\n");
    o.push_str("    pub const fn all() -> Self {\n");
    o.push_str("        Self(Self::KHR_REGION.0 | Self::EXTENSION_REGION.0)\n");
    o.push_str("    }\n");

    o.push_str("\n    /// Defined lobes in canonical low-bit-first pack order.\n");
    o.push_str("    pub(crate) const fn canonical() -> [Self; Self::COUNT as usize] {\n");
    o.push_str("        [\n");
    for lobe in &lobes {
        let _ = writeln!(o, "            Self::{},", lobe.mask_const);
    }
    o.push_str("        ]\n");
    o.push_str("    }\n");
    o.push_str("}\n\n");

    o.push_str("/// One optional lobe's generated identity, in canonical pack order.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct LobeLayout {\n");
    o.push_str("    /// Human-facing lobe id (schema `id`).\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    /// Globally unique capability id (schema `uid`), stable across\n");
    o.push_str("    /// namespace promotion (§5.4).\n");
    o.push_str("    pub uid: &'static str,\n");
    o.push_str("    /// Matching `LobeMask` associated-constant name.\n");
    o.push_str("    pub mask_const: &'static str,\n");
    o.push_str("    /// Immutable `LobeMask` bit index and low-bit-first pack order.\n");
    o.push_str("    pub registry_slot: u32,\n");
    o.push_str("    /// The concrete `LobeMask` bit value for this registry slot.\n");
    o.push_str("    pub mask_bits: u32,\n");
    o.push_str("    /// `u32` word footprint of the lobe.\n");
    o.push_str("    pub words: usize,\n");
    o.push_str("    /// Governance namespace / bit-region partition key (§5.4).\n");
    o.push_str("    /// `\"KHR\"` is the `OpenPBR` specification core; every other value\n");
    o.push_str("    /// lives in the Prism extension region (§4.5 constraint 2).\n");
    o.push_str("    pub namespace: &'static str,\n");
    o.push_str("    /// Stability level (schema `stability`): `\"stable\"` means the engine\n");
    o.push_str("    /// treats the extension as a contract (required when present),\n");
    o.push_str("    /// `\"experimental\"` means optional / gracefully degradable (§5.3).\n");
    o.push_str("    pub stability: &'static str,\n");
    o.push_str("    /// Platform capabilities this lobe needs beyond the shared über path\n");
    o.push_str("    /// (§5.3). Empty means \"runs on the baseline über path\".\n");
    o.push_str("    pub requires_caps: &'static [&'static str],\n");
    o.push_str("    /// §17.2 lobe-level energy policy: the rollup of the lobe's\n");
    o.push_str("    /// field-level `energy_policy` column (`coupled` > `independent`\n");
    o.push_str("    /// > `none`). `prism_material_pcm::EnergyPolicy::parse` reads it.\n");
    o.push_str("    pub energy_policy: &'static str,\n");
    o.push_str("}\n\n");
    o.push_str("/// The defined lobes in canonical low-bit-first pack order.\n");
    o.push_str("///\n");
    o.push_str("/// The `KHR`/extension split of this table is the machine-checked form of\n");
    o.push_str("/// the `OpenPBR` bit-region isolation invariant (§4.5 constraint 2):\n");
    o.push_str("/// `surface.rs::LobeMask` derives its region masks from the same schema, and\n");
    o.push_str("/// `layout_matches_generated_table` asserts the two agree.\n");
    let _ = writeln!(o, "pub const SURFACE_LOBES: [LobeLayout; {count}] = [");
    // Emit the rustfmt-canonical multi-line struct literal (rustfmt's default
    // `struct_lit_width = 18` expands these named-field literals), so the
    // committed file is simultaneously codegen output *and* `cargo fmt`-stable
    // and the freshness byte-compare never fights the formatter.
    for lobe in &lobes {
        o.push_str("    LobeLayout {\n");
        let _ = writeln!(o, "        id: {:?},", lobe.id);
        let _ = writeln!(o, "        uid: {:?},", lobe.uid);
        let _ = writeln!(o, "        mask_const: {:?},", lobe.mask_const);
        let _ = writeln!(o, "        registry_slot: {},", lobe.registry_slot);
        let _ = writeln!(o, "        mask_bits: {},", 1u32 << lobe.registry_slot);
        let _ = writeln!(o, "        words: {},", lobe.words);
        let _ = writeln!(o, "        namespace: {:?},", lobe.namespace.as_str());
        let caps: Vec<String> = lobe
            .requires_caps
            .iter()
            .map(|c| format!("{c:?}"))
            .collect();
        let _ = writeln!(o, "        stability: {:?},", lobe.stability.as_str());
        emit_string_slice_field(&mut o, "requires_caps", &caps);
        let _ = writeln!(
            o,
            "        energy_policy: {:?},",
            energy_policy_str(lobe_energy_policy(lobe))
        );
        o.push_str("    },\n");
    }
    o.push_str("];\n");

    // The lobe → authored closure implementation link is a build-time fact.
    let closures: Vec<String> = lobes
        .iter()
        .filter_map(|lobe| {
            lobe.closure
                .as_ref()
                .map(|closure| format!("({:?}, {closure:?})", lobe.id))
        })
        .collect();
    o.push_str("\n/// Build-time lobe → closure implementation relationships.\n");
    o.push_str("/// Shared implementations do not imply shared runtime identity.\n");
    if closures.is_empty() {
        o.push_str("pub const SURFACE_LOBE_CLOSURES: [(&str, &str); 0] = [];\n");
    } else {
        let _ = writeln!(
            o,
            "pub const SURFACE_LOBE_CLOSURES: [(&str, &str); {}] = [",
            closures.len()
        );
        for closure in &closures {
            let _ = writeln!(o, "    {closure},");
        }
        o.push_str("];\n");
    }

    // A typo or removed IR implementation must fail the Rust build, rather
    // than silently fall through a runtime classifier. No second spelling
    // registry is maintained by the generator.
    o.push_str("\n// Type-check every declared closure implementation at build time.\n");
    o.push_str("const _: &[crate::ir::ClosureKind] = &[\n");
    for lobe in &lobes {
        if let Some(closure) = &lobe.closure {
            let _ = writeln!(o, "    crate::ir::ClosureKind::{closure},");
        }
    }
    o.push_str("];\n");

    // Runtime dynamic parameter channels (§17.1): declared by the same schema as
    // the lobes, so the ABI mirror gate, the PCM catalogue and this table all
    // read one declaration instead of three hand-written lists.
    o.push_str("\n/// One runtime dynamic channel's generated identity.\n");
    o.push_str("///\n");
    o.push_str("/// The value lives in one of the material header's `dynamic_*` words;\n");
    o.push_str("/// `header_word` is that word's index, in declaration order.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\n");
    o.push_str("pub struct ChannelLayout {\n");
    o.push_str("    /// Human-facing channel id (schema `id`).\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    /// Globally unique capability id (schema `uid`).\n");
    o.push_str("    pub uid: &'static str,\n");
    o.push_str("    /// Header-digest slot (immutable; §5.4).\n");
    o.push_str("    pub registry_slot: u32,\n");
    o.push_str("    /// Governance namespace (schema `namespace`).\n");
    o.push_str("    pub namespace: &'static str,\n");
    o.push_str("    /// Vendor tag (schema `vendor`).\n");
    o.push_str("    pub vendor: &'static str,\n");
    o.push_str("    /// Stability level (schema `stability`).\n");
    o.push_str("    pub stability: &'static str,\n");
    o.push_str("    /// Index of the header's `dynamic_*` word carrying the value.\n");
    o.push_str("    pub header_word: u32,\n");
    o.push_str("    /// Neutral default (the value at which the channel is inert).\n");
    o.push_str("    pub default: f32,\n");
    o.push_str("    /// Platform capabilities required beyond the baseline.\n");
    o.push_str("    pub requires_caps: &'static [&'static str],\n");
    o.push_str("    /// Whether the channel's effect changes with the view direction.\n");
    o.push_str("    pub view_dependent: bool,\n");
    o.push_str("}\n\n");
    let mut channels = schema.channels.clone();
    channels.sort_by_key(|channel| channel.header_word);
    let _ = writeln!(
        o,
        "/// The runtime dynamic channels in header-word order.\npub const SURFACE_CHANNELS: [ChannelLayout; {}] = [",
        channels.len()
    );
    for channel in &channels {
        o.push_str("    ChannelLayout {\n");
        let _ = writeln!(o, "        id: {:?},", channel.id);
        let _ = writeln!(o, "        uid: {:?},", channel.uid);
        let _ = writeln!(o, "        registry_slot: {},", channel.registry_slot);
        let _ = writeln!(o, "        namespace: {:?},", channel.namespace.as_str());
        let _ = writeln!(o, "        vendor: {:?},", channel.vendor);
        let _ = writeln!(o, "        stability: {:?},", channel.stability.as_str());
        let _ = writeln!(o, "        header_word: {},", channel.header_word);
        let defaults = channel.default.components();
        let _ = writeln!(o, "        default: {},", float_literal(defaults[0]));
        let caps: Vec<String> = channel
            .requires_caps
            .iter()
            .map(|capability| format!("{capability:?}"))
            .collect();
        let _ = writeln!(o, "        requires_caps: &[{}],", caps.join(", "));
        let _ = writeln!(o, "        view_dependent: {},", channel.view_dependent);
        o.push_str("    },\n");
    }
    o.push_str("];\n");

    // Object-space cache auxiliary outputs (§14.3): header-resident rows with
    // no per-material payload, so their generated identity is the whole
    // declaration.
    o.push_str("\n/// One object-space cache auxiliary's generated identity.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct CacheAuxLayout {\n");
    o.push_str("    /// Human-facing cache-aux id (schema `id`).\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    /// Globally unique capability id (schema `uid`).\n");
    o.push_str("    pub uid: &'static str,\n");
    o.push_str("    /// Header-digest slot (immutable; §5.4).\n");
    o.push_str("    pub registry_slot: u32,\n");
    o.push_str("    /// Governance namespace (schema `namespace`).\n");
    o.push_str("    pub namespace: &'static str,\n");
    o.push_str("    /// Vendor tag (schema `vendor`).\n");
    o.push_str("    pub vendor: &'static str,\n");
    o.push_str("    /// Stability level (schema `stability`).\n");
    o.push_str("    pub stability: &'static str,\n");
    o.push_str("    /// Platform capabilities required beyond the baseline.\n");
    o.push_str("    pub requires_caps: &'static [&'static str],\n");
    o.push_str("    /// Whether the cached quantity changes with the view direction.\n");
    o.push_str("    pub view_dependent: bool,\n");
    o.push_str("}\n\n");
    let mut cache_aux = schema.cache_aux.clone();
    cache_aux.sort_by_key(|aux| aux.registry_slot);
    let _ = writeln!(
        o,
        "/// The object-space cache auxiliaries in registry-slot order."
    );
    if cache_aux.len() == 1 {
        let _ = writeln!(
            o,
            "pub const SURFACE_CACHE_AUX: [CacheAuxLayout; 1] = [CacheAuxLayout {{"
        );
    } else {
        let _ = writeln!(
            o,
            "pub const SURFACE_CACHE_AUX: [CacheAuxLayout; {}] = [",
            cache_aux.len()
        );
    }
    for aux in &cache_aux {
        if cache_aux.len() != 1 {
            o.push_str("    CacheAuxLayout {\n");
        }
        let indent = if cache_aux.len() == 1 {
            "    "
        } else {
            "        "
        };
        let _ = writeln!(o, "{indent}id: {:?},", aux.id);
        let _ = writeln!(o, "{indent}uid: {:?},", aux.uid);
        let _ = writeln!(o, "{indent}registry_slot: {},", aux.registry_slot);
        let _ = writeln!(o, "{indent}namespace: {:?},", aux.namespace.as_str());
        let _ = writeln!(o, "{indent}vendor: {:?},", aux.vendor);
        let _ = writeln!(o, "{indent}stability: {:?},", aux.stability.as_str());
        let caps: Vec<String> = aux
            .requires_caps
            .iter()
            .map(|capability| format!("{capability:?}"))
            .collect();
        let _ = writeln!(o, "{indent}requires_caps: &[{}],", caps.join(", "));
        let _ = writeln!(o, "{indent}view_dependent: {},", aux.view_dependent);
        if cache_aux.len() != 1 {
            o.push_str("    },\n");
        }
    }
    if cache_aux.len() == 1 {
        o.push_str("}];\n");
    } else {
        o.push_str("];\n");
    }

    // Bake/pass-time identity-only extensions (§5.2): no registry slot, no
    // per-material payload; the generated table is the manifest's
    // identity/governance/capability contract.
    o.push_str("\n/// One bake/pass-time extension's generated manifest identity.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct IdentityExtensionLayout {\n");
    o.push_str("    /// Human-facing extension id (schema `id`).\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    /// Globally unique capability id (schema `uid`).\n");
    o.push_str("    pub uid: &'static str,\n");
    o.push_str("    /// Canonical PCM kind spelling (schema `kind`).\n");
    o.push_str("    pub kind: &'static str,\n");
    o.push_str("    /// Governance namespace (schema `namespace`).\n");
    o.push_str("    pub namespace: &'static str,\n");
    o.push_str("    /// Vendor tag (schema `vendor`).\n");
    o.push_str("    pub vendor: &'static str,\n");
    o.push_str("    /// Stability level (schema `stability`).\n");
    o.push_str("    pub stability: &'static str,\n");
    o.push_str("    /// Platform capabilities required beyond the baseline.\n");
    o.push_str("    pub requires_caps: &'static [&'static str],\n");
    o.push_str("    /// Whether the produced result changes with the view direction.\n");
    o.push_str("    pub view_dependent: bool,\n");
    o.push_str("}\n\n");
    let mut identity_extensions = schema.identity_extensions.clone();
    identity_extensions.sort_by(|a, b| {
        a.kind
            .cmp(&b.kind)
            .then_with(|| a.id.as_str().cmp(b.id.as_str()))
    });
    let _ = writeln!(
        o,
        "/// Bake/pass-time identity extensions, grouped by kind then id.\npub const SURFACE_IDENTITY_EXTENSIONS: [IdentityExtensionLayout; {}] = [",
        identity_extensions.len()
    );
    for extension in &identity_extensions {
        o.push_str("    IdentityExtensionLayout {\n");
        let _ = writeln!(o, "        id: {:?},", extension.id);
        let _ = writeln!(o, "        uid: {:?},", extension.uid);
        let _ = writeln!(o, "        kind: {:?},", extension.kind.as_str());
        let _ = writeln!(o, "        namespace: {:?},", extension.namespace.as_str());
        let _ = writeln!(o, "        vendor: {:?},", extension.vendor);
        let _ = writeln!(o, "        stability: {:?},", extension.stability.as_str());
        let caps: Vec<String> = extension
            .requires_caps
            .iter()
            .map(|capability| format!("{capability:?}"))
            .collect();
        let _ = writeln!(o, "        requires_caps: &[{}],", caps.join(", "));
        let _ = writeln!(o, "        view_dependent: {},", extension.view_dependent);
        o.push_str("    },\n");
    }
    o.push_str("];\n");

    // Runtime response programs (§5.2): emit the complete five-contract
    // manifest, not only identity metadata. The generated tables are the
    // bridge consumed by `prism_render_material::ResponseManifest`.
    o.push_str("\n/// One lobe's generated response coverage.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct ResponseLobeLayout {\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    pub supported: bool,\n");
    o.push_str("    pub ignored_reason: Option<&'static str>,\n");
    o.push_str("}\n\n");
    o.push_str("/// A mapped field in a generated response contract.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct ResponseFieldMappingLayout {\n");
    o.push_str("    pub lobe: Option<&'static str>,\n");
    o.push_str("    pub name: &'static str,\n");
    o.push_str("    pub semantic: &'static str,\n");
    o.push_str("    pub test: &'static str,\n");
    o.push_str("}\n\n");
    o.push_str("/// An intentionally unmapped field in a generated response contract.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct ResponseIgnoredFieldLayout {\n");
    o.push_str("    pub lobe: Option<&'static str>,\n");
    o.push_str("    pub name: &'static str,\n");
    o.push_str("    pub reason: &'static str,\n");
    o.push_str("}\n\n");
    o.push_str("/// One runtime response program's complete generated manifest.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct ResponseProgramLayout {\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    pub uid: &'static str,\n");
    o.push_str("    pub registry_slot: u32,\n");
    o.push_str("    pub namespace: &'static str,\n");
    o.push_str("    pub vendor: &'static str,\n");
    o.push_str("    pub stability: &'static str,\n");
    o.push_str("    pub builtin: &'static str,\n");
    o.push_str("    pub requires_caps: &'static [&'static str],\n");
    o.push_str("    pub view_dependent: bool,\n");
    o.push_str("    pub lobes: &'static [ResponseLobeLayout],\n");
    o.push_str("    pub field_mappings: &'static [ResponseFieldMappingLayout],\n");
    o.push_str("    pub ignored_fields: &'static [ResponseIgnoredFieldLayout],\n");
    o.push_str("    pub direct_light: bool,\n");
    o.push_str("    pub shadows: bool,\n");
    o.push_str("    pub indirect_diffuse: bool,\n");
    o.push_str("    pub reflection: bool,\n");
    o.push_str("    pub transmission: bool,\n");
    o.push_str("    pub temporal_history: bool,\n");
    o.push_str("    pub produced_channels: &'static [&'static str],\n");
    o.push_str("    pub blendable_channels: &'static [&'static str],\n");
    o.push_str("    pub supports_fused: bool,\n");
    o.push_str("    pub supports_split: bool,\n");
    o.push_str("    pub max_cost_class: &'static str,\n");
    o.push_str("    pub cache_reads: &'static [&'static str],\n");
    o.push_str("    pub cache_writes: &'static [&'static str],\n");
    o.push_str("    pub cache_temporal: &'static str,\n");
    o.push_str("}\n\n");

    let mut response_programs = schema.response_programs.clone();
    response_programs.sort_by_key(|program| program.registry_slot);
    for program in &response_programs {
        let prefix = format!("RESPONSE_{}", program.builtin.as_str().to_ascii_uppercase());
        let _ = writeln!(
            o,
            "const {prefix}_LOBES: [ResponseLobeLayout; {}] = [",
            lobes.len()
        );
        for lobe in &lobes {
            let reason = program.surface.ignored_lobes.get(&lobe.id);
            emit_response_lobe(
                &mut o,
                &lobe.id,
                reason.is_none(),
                reason.as_deref().map(String::as_str),
            );
        }
        o.push_str("];\n");

        let fields: Vec<_> = schema.response_fields();
        let mapped = fields
            .iter()
            .filter_map(|(owner, field)| match field.responses.get(&program.id) {
                Some(FieldResponse::Mapped { semantic, test }) => {
                    Some((*owner, *field, semantic, test))
                }
                _ => None,
            })
            .collect::<Vec<_>>();
        let ignored = fields
            .iter()
            .filter_map(|(owner, field)| match field.responses.get(&program.id) {
                Some(FieldResponse::IntentionallyUnmapped { reason }) => {
                    Some((*owner, *field, reason))
                }
                _ => None,
            })
            .collect::<Vec<_>>();
        if mapped.is_empty() {
            let _ = writeln!(
                o,
                "const {prefix}_MAPPED_FIELDS: [ResponseFieldMappingLayout; 0] = [];"
            );
        } else {
            let _ = writeln!(
                o,
                "const {prefix}_MAPPED_FIELDS: [ResponseFieldMappingLayout; {}] = [",
                mapped.len()
            );
            for (owner, field, semantic, test) in mapped {
                let owner = owner
                    .map(|value| format!("Some({value:?})"))
                    .unwrap_or_else(|| "None".into());
                let _ = writeln!(
                    o,
                    "    ResponseFieldMappingLayout {{ lobe: {owner}, name: {:?}, semantic: {:?}, test: {:?} }},",
                    field.name, semantic, test
                );
            }
            o.push_str("];\n");
        }
        let _ = writeln!(
            o,
            "const {prefix}_IGNORED_FIELDS: [ResponseIgnoredFieldLayout; {}] = [",
            ignored.len()
        );
        for (owner, field, reason) in ignored {
            let owner = owner
                .map(|value| format!("Some({value:?})"))
                .unwrap_or_else(|| "None".into());
            emit_response_ignored_field(&mut o, &owner, &field.name, reason);
        }
        o.push_str("];\n\n");
    }

    let _ = writeln!(
        o,
        "/// The runtime response programs in registry-slot order.\npub const SURFACE_RESPONSE_PROGRAMS: [ResponseProgramLayout; {}] = [",
        response_programs.len()
    );
    for program in &response_programs {
        let prefix = format!("RESPONSE_{}", program.builtin.as_str().to_ascii_uppercase());
        let caps: Vec<String> = program
            .requires_caps
            .iter()
            .map(|capability| format!("{capability:?}"))
            .collect();
        let produced: Vec<String> = program
            .output
            .produced_channels
            .iter()
            .map(|channel| format!("{:?}", channel.as_str()))
            .collect();
        let blendable: Vec<String> = program
            .output
            .blendable_channels
            .iter()
            .map(|channel| format!("{:?}", channel.as_str()))
            .collect();
        let reads: Vec<String> = program
            .cache
            .reads
            .iter()
            .map(|channel| format!("{:?}", channel.as_str()))
            .collect();
        let writes: Vec<String> = program
            .cache
            .writes
            .iter()
            .map(|channel| format!("{:?}", channel.as_str()))
            .collect();
        let _ = writeln!(o, "    ResponseProgramLayout {{");
        let _ = writeln!(o, "        id: {:?},", program.id);
        let _ = writeln!(o, "        uid: {:?},", program.uid);
        let _ = writeln!(o, "        registry_slot: {},", program.registry_slot);
        let _ = writeln!(o, "        namespace: {:?},", program.namespace.as_str());
        let _ = writeln!(o, "        vendor: {:?},", program.vendor);
        let _ = writeln!(o, "        stability: {:?},", program.stability.as_str());
        let _ = writeln!(o, "        builtin: {:?},", program.builtin.as_str());
        let _ = writeln!(o, "        requires_caps: &[{}],", caps.join(", "));
        let _ = writeln!(o, "        view_dependent: {},", program.view_dependent);
        let _ = writeln!(o, "        lobes: &{prefix}_LOBES,");
        let _ = writeln!(o, "        field_mappings: &{prefix}_MAPPED_FIELDS,");
        let _ = writeln!(o, "        ignored_fields: &{prefix}_IGNORED_FIELDS,");
        let _ = writeln!(
            o,
            "        direct_light: {},",
            program.lighting.direct_light
        );
        let _ = writeln!(o, "        shadows: {},", program.lighting.shadows);
        let _ = writeln!(
            o,
            "        indirect_diffuse: {},",
            program.lighting.indirect_diffuse
        );
        let _ = writeln!(o, "        reflection: {},", program.lighting.reflection);
        let _ = writeln!(
            o,
            "        transmission: {},",
            program.lighting.transmission
        );
        let _ = writeln!(
            o,
            "        temporal_history: {},",
            program.lighting.temporal_history
        );
        emit_string_slice_field(&mut o, "produced_channels", &produced);
        emit_string_slice_field(&mut o, "blendable_channels", &blendable);
        let _ = writeln!(
            o,
            "        supports_fused: {},",
            program.execution.supports_fused
        );
        let _ = writeln!(
            o,
            "        supports_split: {},",
            program.execution.supports_split
        );
        let _ = writeln!(
            o,
            "        max_cost_class: {:?},",
            program.execution.max_cost_class.as_str()
        );
        emit_string_slice_field(&mut o, "cache_reads", &reads);
        emit_string_slice_field(&mut o, "cache_writes", &writes);
        let _ = writeln!(
            o,
            "        cache_temporal: {:?},",
            program.cache.temporal.as_str()
        );
        o.push_str("    },\n");
    }
    o.push_str("];\n");

    // Response contracts use the same authoritative schema field identities as
    // the GPU decoder. Padding is storage, not a surface input. Keeping this
    // directory generated prevents a second, incomplete hand-written catalogue
    // from accidentally making field-coverage validation vacuous.
    let field_count = schema
        .core
        .fields
        .iter()
        .filter(|field| field.ty != FieldType::Pad)
        .count()
        + lobes
            .iter()
            .map(|lobe| {
                lobe.fields
                    .iter()
                    .filter(|field| field.ty != FieldType::Pad)
                    .count()
            })
            .sum::<usize>();
    o.push_str("\n/// One non-padding input field of the surface ABI.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct SurfaceFieldLayout {\n");
    o.push_str("    /// `None` for the always-present core, otherwise the schema lobe id.\n");
    o.push_str("    pub lobe: Option<&'static str>,\n");
    o.push_str("    /// Field name within the owning record.\n");
    o.push_str("    pub name: &'static str,\n");
    o.push_str("    /// Target member in the decoded CPU/GPU fat surface.\n");
    o.push_str("    pub surface_field: &'static str,\n");
    o.push_str("    /// Exact schema storage type (`f32`, `vec4f`, or `f16`).\n");
    o.push_str("    pub storage_type: &'static str,\n");
    o.push_str("    /// First `u32` word within the owning record.\n");
    o.push_str("    pub pack_slot: u32,\n");
    o.push_str("    /// Word footprint of the field's storage type.\n");
    o.push_str("    pub words: u32,\n");
    o.push_str("    /// Schema bit-region spelling (`KHR`, `PRISM`, ...).\n");
    o.push_str("    pub bit_region: &'static str,\n");
    o.push_str("    /// Declared pipeline consumers, in schema order.\n");
    o.push_str("    pub consumed_by: &'static [&'static str],\n");
    o.push_str("}\n\n");
    let _ = writeln!(o, "/// Every non-padding field, in core-then-registry-slot order.\npub const SURFACE_FIELDS: [SurfaceFieldLayout; {field_count}] = [");
    for field in schema
        .core
        .fields
        .iter()
        .filter(|field| field.ty != FieldType::Pad)
    {
        let _ = writeln!(
            o,
            "    SurfaceFieldLayout {{\n        lobe: None,\n        name: {:?},\n        surface_field: {:?},\n        storage_type: {:?},\n        pack_slot: {},\n        words: {},\n        bit_region: {:?},\n        consumed_by: &{:?},\n    }},",
            field.name,
            field.surface_field(),
            field.ty.as_str(),
            field.pack_slot,
            field.ty.words(),
            field.bit_region.as_str(),
            field
                .consumed_by
                .iter()
                .map(|step| step.as_str())
                .collect::<Vec<_>>()
        );
    }
    for lobe in lobes {
        for field in lobe
            .fields
            .iter()
            .filter(|field| field.ty != FieldType::Pad)
        {
            let _ = writeln!(
                o,
                "    SurfaceFieldLayout {{\n        lobe: Some({:?}),\n        name: {:?},\n        surface_field: {:?},\n        storage_type: {:?},\n        pack_slot: {},\n        words: {},\n        bit_region: {:?},\n        consumed_by: &{:?},\n    }},",
                lobe.id,
                field.name,
                field.surface_field(),
                field.ty.as_str(),
                field.pack_slot,
                field.ty.words(),
                field.bit_region.as_str(),
                field
                    .consumed_by
                    .iter()
                    .map(|step| step.as_str())
                    .collect::<Vec<_>>()
            );
        }
    }
    o.push_str("];\n");
    o
}

