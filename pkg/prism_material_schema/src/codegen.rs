/// Emit the generated Rust layout module consumed by
/// `prism_render_material::surface` (constants + the canonical lobe table).
///
/// The output is byte-stable and ends with a trailing newline. It deliberately
/// contains *no behaviour*, only the layout facts the hand-written typed structs
/// are checked against: word counts, the lobe count, the worst-case word count,
/// and the canonical `(id, mask_const, registry_slot, words)` table in pack
/// order.
#[must_use]
pub fn emit_rust_layout(schema: &SurfaceSchema) -> String {
    let core_words = schema.core.words;
    let lobe_words = uniform_lobe_words(schema);
    let count = schema.lobe_count();
    let max_words = schema.packed_len_words(all_lobe_bits(schema));
    let lobes = schema.canonical_lobes();

    let mut o = String::with_capacity(2048);
    let _ = writeln!(o, "// {GENERATED_BANNER_LINE}");
    let _ = writeln!(o, "// Regenerate: {REGEN_COMMAND}");
    o.push_str("//! Generated über-BSDF surface layout facts (design doc §17.5, stage S2).\n");
    o.push_str("//!\n");
    o.push_str("//! The single declarative source of truth is `schema/surface.toml` in\n");
    o.push_str("//! `prism_material_schema`. This module exports the layout constants and the\n");
    o.push_str(
        "//! canonical lobe table so the hand-written typed structs in `surface.rs` can be\n",
    );
    o.push_str(
        "//! checked against — never diverge from — the schema. Edit the schema, not this.\n",
    );
    o.push('\n');
    o.push_str("/// Number of `u32` words in the always-present surface core.\n");
    let _ = writeln!(o, "pub const SURFACE_CORE_WORDS: usize = {core_words};");
    o.push_str("/// Number of `u32` words in every uniform per-lobe quantum.\n");
    let _ = writeln!(o, "pub const SURFACE_LOBE_WORDS: usize = {lobe_words};");
    o.push_str("/// Number of defined optional lobes (equals `LobeMask::COUNT`).\n");
    let _ = writeln!(o, "pub const SURFACE_LOBE_COUNT: u32 = {count};");
    o.push_str(
        "/// Fully-loaded worst case: core plus every lobe. The WESL decoder gathers into\n",
    );
    o.push_str("/// an `array<u32, SURFACE_MAX_WORDS>`.\n");
    let _ = writeln!(o, "pub const SURFACE_MAX_WORDS: usize = {max_words};");
    o.push('\n');
    o.push_str("/// One optional lobe's generated identity, in canonical pack order.\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n");
    o.push_str("pub struct LobeLayout {\n");
    o.push_str("    /// Human-facing lobe id (schema `id`).\n");
    o.push_str("    pub id: &'static str,\n");
    o.push_str("    /// Matching `LobeMask` associated-constant name.\n");
    o.push_str("    pub mask_const: &'static str,\n");
    o.push_str("    /// Immutable `LobeMask` bit index and low-bit-first pack order.\n");
    o.push_str("    pub registry_slot: u32,\n");
    o.push_str("    /// `u32` word footprint of the lobe.\n");
    o.push_str("    pub words: usize,\n");
    o.push_str("}\n\n");
    o.push_str("/// The defined lobes in canonical low-bit-first pack order.\n");
    let _ = writeln!(o, "pub const SURFACE_LOBES: [LobeLayout; {count}] = [");
    // Emit the rustfmt-canonical multi-line struct literal (rustfmt's default
    // `struct_lit_width = 18` expands these named-field literals), so the
    // committed file is simultaneously codegen output *and* `cargo fmt`-stable
    // and the freshness byte-compare never fights the formatter.
    for lobe in &lobes {
        o.push_str("    LobeLayout {\n");
        let _ = writeln!(o, "        id: {:?},", lobe.id);
        let _ = writeln!(o, "        mask_const: {:?},", lobe.mask_const);
        let _ = writeln!(o, "        registry_slot: {},", lobe.registry_slot);
        let _ = writeln!(o, "        words: {},", lobe.words);
        o.push_str("    },\n");
    }
    o.push_str("];\n");
    o
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::surface_schema;

    #[test]
    fn float_literal_always_has_a_point() {
        assert_eq!(float_literal(1.0), "1.0");
        assert_eq!(float_literal(0.0), "0.0");
        assert_eq!(float_literal(0.5), "0.5");
        assert_eq!(float_literal(1.5), "1.5");
        assert_eq!(float_literal(0.1), "0.1");
    }

    #[test]
    fn wesl_emitter_is_deterministic() {
        let schema = surface_schema();
        assert_eq!(emit_wesl_unpack(&schema), emit_wesl_unpack(&schema));
    }

    #[test]
    fn rust_emitter_is_deterministic() {
        let schema = surface_schema();
        assert_eq!(emit_rust_layout(&schema), emit_rust_layout(&schema));
    }

    #[test]
    fn wesl_exposes_the_consumer_api() {
        let wesl = emit_wesl_unpack(&surface_schema());
        for needle in [
            "fn prism_unpack_surface(words: array<u32, 40>, lobe_mask: u32)",
            "fn prism_packed_word_count(lobe_mask: u32) -> u32",
            "fn prism_neutral_surface() -> PrismSurfaceParameters",
            "const PRISM_SURFACE_MAX_WORDS: u32 = 40u;",
            "import prism_render_scene::shaders::material::PrismSurfaceParameters;",
        ] {
            assert!(wesl.contains(needle), "generated WESL missing `{needle}`");
        }
        // The face lobe uses the namespaced fat-struct field.
        assert!(wesl.contains("s.face_softness = bitcast<f32>(w[cursor]);"));
        // Both twins end with a trailing newline.
        assert!(wesl.ends_with('\n'));
    }

    #[test]
    fn wesl_neutral_matches_schema_defaults() {
        let wesl = emit_wesl_unpack(&surface_schema());
        // Spot-check a few defaults the hand-written file is known to carry.
        assert!(wesl.contains("s.base_color = vec4<f32>(1.0, 1.0, 1.0, 1.0);"));
        assert!(wesl.contains("s.index_of_refraction = 1.5;"));
        assert!(wesl.contains("s.face_softness = 0.1;"));
        assert!(wesl.contains("s.perceptual_roughness = 0.5;"));
    }

    #[test]
    fn rust_layout_exposes_constants_and_table() {
        let rust = emit_rust_layout(&surface_schema());
        for needle in [
            "pub const SURFACE_CORE_WORDS: usize = 12;",
            "pub const SURFACE_LOBE_WORDS: usize = 4;",
            "pub const SURFACE_LOBE_COUNT: u32 = 7;",
            "pub const SURFACE_MAX_WORDS: usize = 40;",
            "pub const SURFACE_LOBES: [LobeLayout; 7] = [",
            "    LobeLayout {\n        id: \"emission\",\n        mask_const: \"EMISSION\",\n        registry_slot: 0,\n        words: 4,\n    },",
            "    LobeLayout {\n        id: \"face\",\n        mask_const: \"FACE\",\n        registry_slot: 6,\n        words: 4,\n    },",
        ] {
            assert!(rust.contains(needle), "generated Rust missing `{needle}`");
        }
        assert!(rust.ends_with('\n'));
    }
}
