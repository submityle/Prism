/// Emit the full `material_unpack.wesl` module from the schema.
///
/// The output is byte-stable and ends with a trailing newline. It defines the
/// per-lobe bit constants, the core/lobe word counts and worst-case word count,
/// `prism_packed_word_count`, `prism_neutral_surface`, and `prism_unpack_surface`
/// — the exact public surface the five scene consumers import.
#[must_use]
pub fn emit_wesl_unpack(schema: &SurfaceSchema) -> String {
    let core_words = schema.core.words;
    let lobe_words = uniform_lobe_words(schema);
    let count = schema.lobe_count();
    let max_words = schema.packed_len_words(all_lobe_bits(schema));
    let lobes = schema.canonical_lobes();

    let mut o = String::with_capacity(4096);

    // --- header -----------------------------------------------------------
    let _ = writeln!(o, "//! {GENERATED_BANNER_LINE}");
    let _ = writeln!(o, "//! Regenerate: {REGEN_COMMAND}");
    o.push_str("//!\n");
    o.push_str(
        "//! Variable-length material parameter word-heap decode (design doc §3.3 / §17.5).\n",
    );
    o.push_str("//!\n");
    o.push_str("//! Byte-exact WESL twin of\n");
    o.push_str(
        "//! `prism_render_material::SurfaceParameterBlock::unpack(mask, words).to_full()`:\n",
    );
    let _ = writeln!(
        o,
        "//! the scene packs each surface as an über-BSDF core ({core_words} words) followed by"
    );
    o.push_str(
        "//! only the lobes named in `lobe_mask`, written low bit first. Readers gather the\n",
    );
    o.push_str(
        "//! material's `parameter_size / 4` words out of the shared `array<u32>` heap into a\n",
    );
    let _ = writeln!(
        o,
        "//! fixed `array<u32, {max_words}>` (the fully-loaded worst case) and expand them back to"
    );
    o.push_str(
        "//! a full `PrismSurfaceParameters`, filling absent lobes with neutral defaults.\n",
    );
    o.push_str("//!\n");
    o.push_str(
        "//! Kept as a single generated source so all five consumers (opaque, transparent,\n",
    );
    o.push_str("//! visibility, shading_resolve, ssr_repack) decode identically.\n");
    o.push('\n');
    o.push_str("import prism_render_scene::shaders::material::PrismSurfaceParameters;\n");
    o.push('\n');

    // --- lobe bit constants ----------------------------------------------
    // Build every declaration first, then pad to the widest so the trailing
    // `// 1 << n` comments align into one column.
    let all_bits = all_lobe_bits(schema);
    let mut decls: Vec<(String, String)> = Vec::new();
    for lobe in &lobes {
        let bit = 1u32 << lobe.registry_slot;
        decls.push((
            format!("const PRISM_LOBE_{}: u32 = {bit}u;", lobe.mask_const),
            format!("// 1 << {}", lobe.registry_slot),
        ));
    }
    decls.push((
        format!("const PRISM_LOBE_ALL: u32 = {all_bits}u;"),
        format!("// (1 << {count}) - 1"),
    ));
    let decl_width = decls.iter().map(|(d, _)| d.len()).max().unwrap_or(0) + 1;
    for (decl, comment) in &decls {
        let _ = writeln!(o, "{decl:<decl_width$}{comment}");
    }
    o.push('\n');

    // --- word counts ------------------------------------------------------
    let _ = writeln!(o, "const PRISM_SURFACE_CORE_WORDS: u32 = {core_words}u;");
    let _ = writeln!(o, "const PRISM_SURFACE_LOBE_WORDS: u32 = {lobe_words}u;");
    let _ = writeln!(
        o,
        "/// Fully-loaded worst case: core + every lobe ({core_words} + {count}*{lobe_words})."
    );
    let _ = writeln!(o, "const PRISM_SURFACE_MAX_WORDS: u32 = {max_words}u;");
    o.push('\n');

    // --- prism_packed_word_count -----------------------------------------
    o.push_str("/// Packed word count for a mask: core plus the uniform lobe stride per present\n");
    o.push_str("/// lobe. Mirrors `SurfaceParameterBlock::packed_len_words`.\n");
    o.push_str("fn prism_packed_word_count(lobe_mask: u32) -> u32 {\n");
    o.push_str("    return PRISM_SURFACE_CORE_WORDS\n");
    o.push_str("        + countOneBits(lobe_mask & PRISM_LOBE_ALL) * PRISM_SURFACE_LOBE_WORDS;\n");
    o.push_str("}\n\n");

    // --- prism_neutral_surface -------------------------------------------
    o.push_str(
        "/// The canonical neutral surface (`GpuSurfaceParameters::default`): the base an\n",
    );
    o.push_str(
        "/// absent lobe decodes back to, and the value returned when a material's declared\n",
    );
    o.push_str("/// range does not fit the bound heap.\n");
    o.push_str("fn prism_neutral_surface() -> PrismSurfaceParameters {\n");
    o.push_str("    var s: PrismSurfaceParameters;\n");
    for field in &schema.core.fields {
        emit_wesl_default(&mut o, field);
    }
    for lobe in &lobes {
        for field in &lobe.fields {
            emit_wesl_default(&mut o, field);
        }
    }
    o.push_str("    return s;\n");
    o.push_str("}\n\n");

    // --- prism_unpack_surface --------------------------------------------
    o.push_str(
        "/// Expand `words` (a material's packed block, low words first) into a full surface\n",
    );
    o.push_str(
        "/// using `lobe_mask`. Words beyond the packed length are ignored; absent lobes keep\n",
    );
    o.push_str("/// their neutral default. Byte-exact twin of\n");
    o.push_str("/// `SurfaceParameterBlock::unpack(mask, words).to_full()`.\n");
    let _ = writeln!(
        o,
        "fn prism_unpack_surface(words: array<u32, {max_words}>, lobe_mask: u32) -> PrismSurfaceParameters {{"
    );
    o.push_str("    var w = words;\n");
    o.push_str("    var s = prism_neutral_surface();\n");
    o.push('\n');
    let pad_slots: Vec<u32> = schema
        .core
        .fields
        .iter()
        .filter(|f| f.ty == FieldType::Pad)
        .map(|f| f.pack_slot)
        .collect();
    if pad_slots.is_empty() {
        let _ = writeln!(o, "    // Core ({core_words} words).");
    } else {
        let words: Vec<String> = pad_slots.iter().map(|n| format!("w[{n}]")).collect();
        let _ = writeln!(
            o,
            "    // Core ({core_words} words); {} are padding.",
            words.join(" and ")
        );
    }
    for field in &schema.core.fields {
        emit_wesl_core_read(&mut o, field);
    }
    o.push('\n');
    o.push_str("    // Present lobes, canonical low-bit-first order, uniform stride each.\n");
    o.push_str("    var cursor: u32 = PRISM_SURFACE_CORE_WORDS;\n");
    for lobe in &lobes {
        let _ = writeln!(
            o,
            "    if (lobe_mask & PRISM_LOBE_{}) != 0u {{",
            lobe.mask_const
        );
        for field in &lobe.fields {
            emit_wesl_lobe_read(&mut o, field);
        }
        o.push_str("        cursor += PRISM_SURFACE_LOBE_WORDS;\n");
        o.push_str("    }\n");
    }
    o.push_str("    return s;\n");
    o.push_str("}\n");

    o
}

/// `w[<n>]` for a core read or `w[cursor + <n>u]` / `w[cursor]` for a lobe read.
fn word_index(base_is_cursor: bool, offset: u32) -> String {
    if base_is_cursor {
        if offset == 0 {
            "w[cursor]".to_string()
        } else {
            format!("w[cursor + {offset}u]")
        }
    } else {
        format!("w[{offset}]")
    }
}

/// Emit one neutral-default assignment, skipping pads.
fn emit_wesl_default(o: &mut String, field: &crate::Field) {
    if field.ty == FieldType::Pad {
        return;
    }
    let target = field.surface_field();
    let comps = field.default.components();
    match field.ty {
        FieldType::Vec4f => {
            let v: Vec<String> = comps.iter().map(|c| float_literal(*c)).collect();
            let _ = writeln!(
                o,
                "    s.{target} = vec4<f32>({}, {}, {}, {});",
                v[0], v[1], v[2], v[3]
            );
        }
        FieldType::F32 | FieldType::F16 => {
            let _ = writeln!(o, "    s.{target} = {};", float_literal(comps[0]));
        }
        FieldType::Pad => unreachable!(),
    }
}

/// Emit one core-field decode (`base = schema pack_slot`, no cursor), skipping pads.
fn emit_wesl_core_read(o: &mut String, field: &crate::Field) {
    emit_wesl_read(o, field, false, field.pack_slot);
}

/// Emit one lobe-field decode relative to `cursor`, skipping pads.
fn emit_wesl_lobe_read(o: &mut String, field: &crate::Field) {
    // Lobe reads are indented one extra level (inside the `if` block).
    let mut tmp = String::new();
    emit_wesl_read(&mut tmp, field, true, field.pack_slot);
    for line in tmp.lines() {
        let _ = writeln!(o, "    {line}");
    }
}

fn emit_wesl_read(o: &mut String, field: &crate::Field, base_is_cursor: bool, slot: u32) {
    if field.ty == FieldType::Pad {
        return;
    }
    let target = field.surface_field();
    match field.ty {
        FieldType::Vec4f => {
            let c0 = word_index(base_is_cursor, slot);
            let c1 = word_index(base_is_cursor, slot + 1);
            let c2 = word_index(base_is_cursor, slot + 2);
            let c3 = word_index(base_is_cursor, slot + 3);
            let _ = writeln!(o, "    s.{target} = vec4<f32>(");
            let _ = writeln!(o, "        bitcast<f32>({c0}),");
            let _ = writeln!(o, "        bitcast<f32>({c1}),");
            let _ = writeln!(o, "        bitcast<f32>({c2}),");
            let _ = writeln!(o, "        bitcast<f32>({c3}),");
            let _ = writeln!(o, "    );");
        }
        FieldType::F32 | FieldType::F16 => {
            let idx = word_index(base_is_cursor, slot);
            let _ = writeln!(o, "    s.{target} = bitcast<f32>({idx});");
        }
        FieldType::Pad => {}
    }
}

