    #[test]
    fn non_uniform_lobes_get_per_lobe_strides() {
        // §4.4: lobes are variable length. Widen one lobe and prove both twins
        // advance by that lobe's own footprint instead of a shared stride — the
        // generalization that lets P1-f grow each lobe to its full OpenPBR field
        // set without a 16-byte-quantum ceiling.
        let mut schema = surface_schema();
        schema
            .lobes
            .iter_mut()
            .find(|lobe| lobe.id == "clearcoat")
            .expect("clearcoat lobe present")
            .words = 20;

        let expected_max = schema.packed_len_words(all_lobe_bits(&schema));

        let rust = emit_rust_layout(&schema);
        assert!(rust.contains("pub const SURFACE_LOBE_WORDS: usize = 20;"));
        // Two dense segments with a reserved gap: canonical 0..6, extension 16+.
        assert!(rust.contains(
            "pub const SURFACE_LOBE_WORDS_BY_SLOT: [usize; 19] =\n    [8, 20, 4, 8, 16, 16, 4, 0, 0, 0, 0, 0, 0, 0, 0, 0, 4, 4, 4];"
        ));
        // Worst case grows with the widened lobe; derive it from the schema so
        // the test does not re-hardcode the other lobes' footprints.
        assert!(rust.contains(&format!(
            "pub const SURFACE_MAX_WORDS: usize = {expected_max};"
        )));

        let wesl = emit_wesl_unpack(&schema);
        assert!(wesl.contains("const PRISM_LOBE_WORDS_CLEARCOAT: u32 = 20u;"));
        assert!(wesl.contains("words += PRISM_LOBE_WORDS_CLEARCOAT;"));
        assert!(wesl.contains("cursor += PRISM_LOBE_WORDS_CLEARCOAT;"));
        assert!(wesl.contains(&format!(
            "fn prism_unpack_surface(words: array<u32, {expected_max}>, lobe_mask: u32)"
        )));
    }
