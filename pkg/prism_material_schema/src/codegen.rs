//! Deterministic code generation from the surface schema (design doc §17.5, S2).
//!
//! Stage S1 only *parity-checked* the hand-written layout against this schema.
//! Stage S2 flips the dependency: the schema becomes the generator. The two
//! emitters here turn the validated [`SurfaceSchema`] into the exact source text
//! of two previously hand-maintained twins:
//!
//! * [`emit_wesl_unpack`] — the GPU word-heap decoder
//!   (`prism_render_scene/src/shaders/material_unpack.wesl`): the lobe-bit
//!   constants, the neutral surface, `prism_packed_word_count` and
//!   `prism_unpack_surface`.
//! * [`emit_rust_layout`] — the CPU layout constants, `LobeMask` layout facts,
//!   and lobe table consumed by `prism_render_material::surface`
//!   (`SURFACE_CORE_WORDS`, `SURFACE_MAX_WORDS`, the canonical
//!   [`SURFACE_LOBES`](crate) table, …).
//!
//! Both emitters are pure functions of the schema, so the generated files are
//! committed and a freshness test (`regenerate == committed`) turns any drift
//! into a red build. Byte parity of the hand-written `surface.rs` struct image
//! is still guarded by the S1 gate in `prism_render_material`, so the schema →
//! Rust layout → WESL chain is transitively byte-exact.
//!
//! The emitters are intentionally *textual*: they never shell out to `rustfmt`
//! or a WESL formatter, so output is reproducible on any host with no toolchain
//! beyond this crate. The layout they encode is small and regular (variable-length
//! lobes packed low-bit-first), which keeps the generated text review-friendly.

use alloc::format;
use alloc::string::{String, ToString};
use alloc::vec::Vec;
use core::fmt::Write as _;

use crate::{EnergyPolicy, FieldResponse, FieldType, Lobe, SurfaceSchema};

/// A machine-readable banner marking a file as generated. Both emitters start
/// with it so humans and tooling can detect a hand edit at a glance.
const GENERATED_BANNER_LINE: &str =
    "DO NOT EDIT — generated by `prism-material-codegen` from schema/surface.toml.";

/// The exact command that regenerates every product; embedded in each banner.
const REGEN_COMMAND: &str =
    "cargo run -p prism_material_schema --bin prism-material-codegen -- write";

/// `rustfmt`'s default `max_width`. The generated Rust is emitted in the shape
/// `rustfmt` would leave it in (see the `SURFACE_LOBE_WORDS_BY_SLOT` emission),
/// so `cargo fmt` is a no-op over the generated file and the committed-vs-
/// regenerated freshness gate stays exact.
const RUSTFMT_MAX_WIDTH: usize = 100;

/// Format an `f32` default as a source float literal with a mandatory decimal
/// point, identical for both WESL and Rust (`1 -> 1.0`, `0.1 -> 0.1`). A plain
/// `{}` can drop the point (`1`), which is a type error in WESL `f32` context,
/// so this guarantees one.
fn float_literal(v: f32) -> String {
    let s = format!("{v:?}");
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}

/// The widest per-lobe word footprint in the schema.
///
/// Lobes are **variable length** (§4.4 "变长打包"): the pack cursor advances by
/// each present lobe's own `words`, never a shared stride. This maximum is used
/// only for the human-facing "worst-case quantum" note and for the legacy
/// `SURFACE_LOBE_WORDS` / `PRISM_SURFACE_LOBE_WORDS` constant, which documents
/// the widest lobe rather than a packing stride.
fn max_lobe_words(schema: &SurfaceSchema) -> u32 {
    schema
        .lobes
        .iter()
        .map(|lobe| lobe.words)
        .max()
        .unwrap_or(0)
}

/// All defined lobe bits OR-ed together (`(1 << count) - 1` for contiguous
/// slots, computed from the actual slots so a sparse registry still works).
fn all_lobe_bits(schema: &SurfaceSchema) -> u32 {
    schema
        .lobes
        .iter()
        .fold(0u32, |acc, l| acc | (1u32 << l.registry_slot))
}

fn bit_mask(bits: u8) -> u64 {
    if bits == 64 {
        u64::MAX
    } else {
        (1u64 << bits) - 1
    }
}

fn specialization_mask(range: crate::BitRange) -> u64 {
    bit_mask(range.bits) << range.shift
}

fn emit_f32_slice(output: &mut String, values: &[f32]) {
    let values = values
        .iter()
        .map(|value| float_literal(*value))
        .collect::<Vec<_>>();
    let _ = writeln!(output, "&[{}],", values.join(", "));
}

fn emit_usize_array(output: &mut String, declaration: &str, values: &[usize]) {
    let values = values.iter().map(usize::to_string).collect::<Vec<_>>();
    let one_line = format!("{declaration} = [{}];", values.join(", "));
    if one_line.chars().count() <= RUSTFMT_MAX_WIDTH {
        let _ = writeln!(output, "{one_line}");
        return;
    }

    let _ = writeln!(output, "{declaration} = [");
    let mut line = String::from("    ");
    for value in values {
        let additional_width = if line.len() == 4 {
            value.len()
        } else {
            value.len() + 2
        };
        if line.len() > 4 && line.len() + additional_width + 1 > RUSTFMT_MAX_WIDTH {
            let _ = writeln!(output, "{line},");
            line.clear();
            line.push_str("    ");
        }
        if line.len() > 4 {
            line.push_str(", ");
        }
        line.push_str(&value);
    }
    if line.len() > 4 {
        let _ = writeln!(output, "{line},");
    }
    output.push_str("];\n");
}

/// Emit the schema-derived CPU sample/golden field directory.
///
/// This product intentionally describes only facts that the surface schema
/// owns: identity, projected member, storage footprint, neutral default and
/// declared consumer steps. It does not invent CPU response mathematics,
/// sampling directions, texture semantics or a `SurfaceSample` projection for
/// fields whose runtime behavior is shade-time derived.
#[must_use]
pub fn emit_cpu_surface_contract(schema: &SurfaceSchema) -> String {
    let fields = schema.response_fields();
    let sample_indices = fields
        .iter()
        .enumerate()
        .filter(|(_, (_, field))| field.consumed_by.contains(&crate::ConsumedStep::Sample))
        .map(|(index, _)| index)
        .collect::<Vec<_>>();
    let golden_indices = fields
        .iter()
        .enumerate()
        .filter(|(_, (_, field))| field.consumed_by.contains(&crate::ConsumedStep::Golden))
        .map(|(index, _)| index)
        .collect::<Vec<_>>();
    let sample_word_count = sample_indices
        .iter()
        .map(|index| fields[*index].1.ty.words())
        .sum::<u32>();
    let golden_word_count = golden_indices
        .iter()
        .map(|index| fields[*index].1.ty.words())
        .sum::<u32>();
    let mut o = String::with_capacity(fields.len() * 260 + 1400);
    let _ = writeln!(o, "// {GENERATED_BANNER_LINE}");
    let _ = writeln!(o, "// Regenerate: {REGEN_COMMAND}");
    o.push_str("// Schema-derived CPU sample/golden surface contract.\n");
    o.push_str("// Only declarative surface facts are generated here; response math remains typed code.\n\n");
    o.push_str("#[derive(Clone, Copy, Debug, PartialEq)]\n");
    o.push_str("pub struct CpuSurfaceField {\n");
    o.push_str("    pub lobe: Option<&'static str>,\n    pub name: &'static str,\n    pub surface_field: &'static str,\n    pub storage_type: &'static str,\n    pub words: u32,\n    pub default: &'static [f32],\n    pub consumed_by: &'static [&'static str],\n}\n\n");
    let _ = writeln!(
        o,
        "pub const CPU_SURFACE_FIELDS: [CpuSurfaceField; {}] = [",
        fields.len()
    );
    for (lobe, field) in fields {
        let consumers = field
            .consumed_by
            .iter()
            .map(|step| format!("{:?}", step.as_str()))
            .collect::<Vec<_>>();
        let _ = writeln!(o, "    CpuSurfaceField {{");
        let _ = writeln!(
            o,
            "        lobe: {},",
            lobe.map(|value| format!("Some({value:?})"))
                .unwrap_or_else(|| "None".to_string())
        );
        let _ = writeln!(o, "        name: {:?},", field.name);
        let _ = writeln!(o, "        surface_field: {:?},", field.surface_field());
        let _ = writeln!(o, "        storage_type: {:?},", field.ty.as_str());
        let _ = writeln!(o, "        words: {},", field.ty.words());
        o.push_str("        default: ");
        emit_f32_slice(&mut o, &field.default.components());
        let _ = writeln!(o, "        consumed_by: &[{}],", consumers.join(", "));
        o.push_str("    },\n");
    }
    o.push_str("];\n\n");
    emit_usize_array(
        &mut o,
        &format!(
            "pub const CPU_SAMPLE_FIELD_INDICES: [usize; {}]",
            sample_indices.len()
        ),
        &sample_indices,
    );
    emit_usize_array(
        &mut o,
        &format!(
            "pub const CPU_GOLDEN_FIELD_INDICES: [usize; {}]",
            golden_indices.len()
        ),
        &golden_indices,
    );
    let _ = writeln!(
        o,
        "pub const CPU_SAMPLE_FIELD_COUNT: usize = CPU_SAMPLE_FIELD_INDICES.len();"
    );
    let _ = writeln!(
        o,
        "pub const CPU_GOLDEN_FIELD_COUNT: usize = CPU_GOLDEN_FIELD_INDICES.len();"
    );
    let _ = writeln!(
        o,
        "pub const CPU_SAMPLE_WORD_COUNT: u32 = {sample_word_count};"
    );
    let _ = writeln!(
        o,
        "pub const CPU_GOLDEN_WORD_COUNT: u32 = {golden_word_count};"
    );
    o.push_str("\n/// Borrow typed CPU surface components in schema directory order.\n");
    o.push_str("/// Field renames and type/arity changes fail at the consuming call site.\n");
    o.push_str("#[macro_export]\nmacro_rules! cpu_surface_components {\n");
    o.push_str("    ($surface:ident) => {{\n");
    let _ = writeln!(
        o,
        "        let components: [&[f32]; {}] = [",
        schema.response_fields().len()
    );
    for (_, field) in schema.response_fields() {
        match field.ty {
            FieldType::F32 | FieldType::F16 => {
                let _ = writeln!(
                    o,
                    "            core::slice::from_ref(&$surface.{}),",
                    field.surface_field()
                );
            }
            FieldType::Vec4f => {
                let _ = writeln!(o, "            &$surface.{},", field.surface_field());
            }
            FieldType::Pad => unreachable!("response_fields excludes padding"),
        }
    }
    o.push_str("        ];\n        components\n    }};\n}\n");
    o
}

/// Replace the schema-owned metadata block in the shipping classification
/// shader while preserving the hand-written execution-table algorithm around
/// it. The replacement is exact and deterministic; missing or duplicated
/// markers are rejected by the codegen caller.
#[must_use]
pub fn emit_material_classification(schema: &SurfaceSchema, template: &str) -> String {
    const BEGIN: &str = "// BEGIN SCHEMA-GENERATED MATERIAL METADATA";
    const END: &str = "// END SCHEMA-GENERATED MATERIAL METADATA";
    assert_eq!(
        template.matches(BEGIN).count(),
        1,
        "material_classification.wesl must contain exactly one schema metadata begin marker"
    );
    assert_eq!(
        template.matches(END).count(),
        1,
        "material_classification.wesl must contain exactly one schema metadata end marker"
    );
    let begin = template
        .find(BEGIN)
        .expect("validated schema metadata begin marker");
    let end_rel = template[begin..]
        .find(END)
        .expect("validated schema metadata end marker");
    let end = begin + end_rel + END.len();
    let block_storage = emit_material_classification_schema_block(schema);
    let block = block_storage.trim_end();
    let mut output = String::with_capacity(template.len() + block.len());
    output.push_str(&template[..begin]);
    output.push_str(block);
    output.push_str(&template[end..]);
    output
}

/// Emit the complete schema contract source product used by S3/S4 tests and
/// tooling. It deliberately contains no runtime dependency on removed APIs.
#[must_use]
pub fn emit_schema_contract(schema: &SurfaceSchema) -> String {
    let mut output = emit_specialization_layout(schema);
    output.push_str(&emit_cpu_surface_contract(schema));
    output
}

/// Emit the schema-derived specialization packing product.
///
/// This is a generated value-level `SpecializationId` contract. It is kept in
/// the schema product rather than the runtime material header: ABI8 carries
/// execution-table bindings, while bake-time keys still need one stable,
/// schema-owned bit packing.
#[must_use]
pub fn emit_specialization_layout(schema: &SurfaceSchema) -> String {
    let layout = &schema.specialization;
    let mut o = String::with_capacity(2200);
    let _ = writeln!(o, "// {GENERATED_BANNER_LINE}");
    let _ = writeln!(o, "// Regenerate: {REGEN_COMMAND}");
    o.push_str("#![allow(missing_docs)]\n\n");
    o.push_str("// Schema-derived bake-time material specialization packing.\n");
    o.push_str("// This is metadata and pure packing logic; it does not restore the removed runtime API.\n\n");
    o.push_str("#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]\n");
    o.push_str("pub struct SpecializationParts {\n");
    o.push_str(
        "    pub illumination: u32,\n    pub lobe_mask: u32,\n    pub render_class: u32,\n}\n\n",
    );
    o.push_str("#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n");
    o.push_str("pub struct SpecializationLayout {\n");
    o.push_str("    pub storage_bits: u8,\n    pub illumination_shift: u8,\n    pub illumination_bits: u8,\n    pub lobe_mask_shift: u8,\n    pub lobe_mask_bits: u8,\n    pub render_class_shift: u8,\n    pub render_class_bits: u8,\n    pub reserved_shift: u8,\n    pub reserved_bits: u8,\n}\n\n");
    o.push_str("pub const SPECIALIZATION_LAYOUT: SpecializationLayout = SpecializationLayout {\n");
    let _ = writeln!(o, "    storage_bits: {},", layout.storage_bits);
    let _ = writeln!(o, "    illumination_shift: {},", layout.illumination.shift);
    let _ = writeln!(o, "    illumination_bits: {},", layout.illumination.bits);
    let _ = writeln!(o, "    lobe_mask_shift: {},", layout.lobe_mask.shift);
    let _ = writeln!(o, "    lobe_mask_bits: {},", layout.lobe_mask.bits);
    let _ = writeln!(o, "    render_class_shift: {},", layout.render_class.shift);
    let _ = writeln!(o, "    render_class_bits: {},", layout.render_class.bits);
    let _ = writeln!(o, "    reserved_shift: {},", layout.reserved.shift);
    let _ = writeln!(o, "    reserved_bits: {},\n}};", layout.reserved.bits);
    let _ = writeln!(
        o,
        "pub const SPECIALIZATION_ILLUMINATION_MASK: u64 = 0x{:016X};",
        specialization_mask(layout.illumination)
    );
    let _ = writeln!(
        o,
        "pub const SPECIALIZATION_LOBE_MASK_MASK: u64 = 0x{:016X};",
        specialization_mask(layout.lobe_mask)
    );
    let _ = writeln!(
        o,
        "pub const SPECIALIZATION_RENDER_CLASS_MASK: u64 = 0x{:016X};",
        specialization_mask(layout.render_class)
    );
    let _ = writeln!(
        o,
        "pub const SPECIALIZATION_RESERVED_MASK: u64 = 0x{:016X};\n",
        specialization_mask(layout.reserved)
    );
    o.push_str("#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n");
    o.push_str("pub struct SpecializationId(u64);\n\n");
    o.push_str("impl SpecializationId {\n");
    o.push_str("    /// Reject out-of-range components instead of silently truncating them.\n");
    o.push_str("    #[must_use]\n");
    o.push_str("    pub const fn try_new(illumination: u32, lobe_mask: u32, render_class: u32) -> Option<Self> {\n");
    for (name, range) in [
        ("illumination", layout.illumination),
        ("lobe_mask", layout.lobe_mask),
        ("render_class", layout.render_class),
    ] {
        if range.bits < 32 {
            let _ = writeln!(
                o,
                "        if {name} > 0x{:X} {{\n            return None;\n        }}",
                bit_mask(range.bits)
            );
        }
    }
    let _ = writeln!(
        o,
        "        Some(Self(\n            ((illumination as u64) << {})\n                | ((lobe_mask as u64) << {})\n                | ((render_class as u64) << {}),\n        ))\n    }}\n",
        layout.illumination.shift, layout.lobe_mask.shift, layout.render_class.shift
    );
    o.push_str("    #[must_use]\n    pub const fn raw(self) -> u64 {\n        self.0\n    }\n\n");
    o.push_str("    #[must_use]\n    pub const fn parts(self) -> SpecializationParts {\n");
    let _ = writeln!(
        o,
        "        SpecializationParts {{\n            illumination: ((self.0 >> {}) & 0x{:X}) as u32,\n            lobe_mask: ((self.0 >> {}) & 0x{:X}) as u32,\n            render_class: ((self.0 >> {}) & 0x{:X}) as u32,\n        }}\n    }}\n",
        layout.illumination.shift,
        bit_mask(layout.illumination.bits),
        layout.lobe_mask.shift,
        bit_mask(layout.lobe_mask.bits),
        layout.render_class.shift,
        bit_mask(layout.render_class.bits)
    );
    o.push_str("    /// Reserved, undeclared and above-storage bits are all invalid.\n");
    o.push_str("    #[must_use]\n    pub const fn from_raw(value: u64) -> Option<Self> {\n");
    o.push_str("        let valid = SPECIALIZATION_ILLUMINATION_MASK\n            | SPECIALIZATION_LOBE_MASK_MASK\n            | SPECIALIZATION_RENDER_CLASS_MASK;\n");
    o.push_str("        if value & !valid == 0 {\n            Some(Self(value))\n        } else {\n            None\n        }\n    }\n}\n\n");
    o
}

/// Emit the schema-owned metadata block embedded in the shipping
/// `material_classification.wesl` consumer.
#[must_use]
pub fn emit_material_classification_schema_block(schema: &SurfaceSchema) -> String {
    let layout = &schema.specialization;
    let mut o = String::new();
    o.push_str("// BEGIN SCHEMA-GENERATED MATERIAL METADATA\n");
    o.push_str("// This block is generated from schema/surface.toml.\n");
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_ILLUMINATION_SHIFT: u32 = {}u;",
        layout.illumination.shift
    );
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_ILLUMINATION_BITS: u32 = {}u;",
        layout.illumination.bits
    );
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_LOBE_MASK_SHIFT: u32 = {}u;",
        layout.lobe_mask.shift
    );
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_LOBE_MASK_BITS: u32 = {}u;",
        layout.lobe_mask.bits
    );
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_RENDER_CLASS_SHIFT: u32 = {}u;",
        layout.render_class.shift
    );
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_RENDER_CLASS_BITS: u32 = {}u;",
        layout.render_class.bits
    );
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_RESERVED_SHIFT: u32 = {}u;",
        layout.reserved.shift
    );
    let _ = writeln!(
        o,
        "const PRISM_SCHEMA_SPECIALIZATION_RESERVED_BITS: u32 = {}u;",
        layout.reserved.bits
    );
    o.push_str("// END SCHEMA-GENERATED MATERIAL METADATA\n");
    o
}

